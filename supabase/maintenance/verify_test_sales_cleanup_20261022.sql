select jsonb_build_object(
  'orders', (select count(*) from public.ordenes),
  'order_items', (select count(*) from public.orden_items),
  'claims', (select count(*) from public.order_claims),
  'batches', (select count(*) from public.dispatch_batches),
  'batch_items', (select count(*) from public.dispatch_batch_items),
  'dispatch_events', (select count(*) from public.dispatch_batch_events),
  'dispatch_blocks', (select count(*) from public.dispatch_blocks),
  'packages', (select count(*) from public.order_packages),
  'preparation_scans', (select count(*) from public.order_preparation_scans),
  'reviews', (select count(*) from public.reviews),
  'resenas', (select count(*) from public.resenas),
  'tracking_events', (select count(*) from public.andreani_tracking_events),
  'claim_shipments', (select count(*) from public.order_claim_shipments),
  'andreani_billing', (select count(*) from public.andreani_billing_entries),
  'arca_invoice_snapshots', (select count(*) from public.arca_invoice_header_snapshots)
    + (select count(*) from public.arca_invoice_item_snapshots),
  'credit_notes', (select count(*) from public.order_credit_notes),
  'mp_refunds', (select count(*) from public.mercadopago_order_refunds),
  'transfer_claims', (select count(*) from public.transfer_verification_payment_claims),
  'credit_movements', (select count(*) from public.customer_credit_movements),
  'notifications', (select count(*) from public.customer_notifications),
  'admin_notification_reads', (select count(*) from public.admin_notification_reads),
  'stock_reservations', (select count(*) from public.stock_reservations),
  'sale_adjustments', (select count(*) from public.inventory_stock_adjustments where idempotency_key like 'replacement:%'),
  'returns', (select count(*) from public.inventory_return_movements),
  'sale_inventory_movements', (select count(*) from public.inventory_movements where source in ('web_sale','approved_return')),
  'sale_operation_logs', (select count(*) from public.inventory_operation_log where source_table in ('orden_items','inventory_return_movements') or source_id like 'replacement:%'),
  'order_audit_logs', (select count(*) from public.audit_logs where table_name in ('ordenes','orden_items','reviews','inventory_return_movements','order_replacements')),
  'unvalidated_foreign_keys', (select count(*) from pg_constraint where contype='f' and connamespace='public'::regnamespace and not convalidated),
  'products', (select count(*) from public.productos),
  'variants', (select count(*) from public.producto_variantes),
  'prices', (select count(*) from public.product_pricing),
  'barcodes', (select count(*) from public.catalog_barcode_registry),
  'skus', (select count(*) from public.catalog_sku_registry),
  'categories', (select count(*) from public.categorias),
  'banner_items', (select count(*) from public.site_banner_items),
  'profiles', (select count(*) from public.profiles),
  'purchases', (select count(*) from public.product_cost_entries),
  'purchase_operation_logs', (select count(*) from public.inventory_operation_log where source_table='product_cost_entries'),
  'orphan_variants', (select count(*) from public.producto_variantes v left join public.productos p on p.id=v.producto_id where p.id is null),
  'orphan_barcode_products', (select count(*) from public.catalog_barcode_registry c left join public.productos p on p.id=c.product_id where c.product_id is not null and p.id is null)
) as verification;
