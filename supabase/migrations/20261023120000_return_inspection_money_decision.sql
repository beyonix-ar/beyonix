-- Devolución después del despacho: el dinero no se devuelve a ciegas.
-- Una cancelación cuyo pedido ya salió de BEYONIX (order_dispatch_cutoff_reached)
-- exige registrar la recepción física y una decisión explícita del Admin:
-- aprobar o rechazar la devolución del dinero. Una cancelación antes del
-- despacho no pasa por acá.
-- Separación de responsabilidades:
--   recepción física  -> order_return_inspections.physical_state
--   decisión de dinero -> order_return_inspections.decision (+ financial_status)
--   obligación fiscal  -> sin cambios (credit_note_required / factura); un
--                         rechazo nunca la borra ni emite una NC con dinero.

-- 1. Estado financiero de una devolución de dinero rechazada ------------------------
alter table public.ordenes drop constraint if exists ordenes_financial_status_check;
alter table public.ordenes add constraint ordenes_financial_status_check check (
  financial_status = any (array['pending_payment','payment_submitted','payment_confirmed',
    'cancellation_requested','refund_pending','refunded','cancelled','refund_rejected']));

alter table public.ordenes drop constraint if exists ordenes_admin_visibility_payment_check;
alter table public.ordenes add constraint ordenes_admin_visibility_payment_check check (
  payment_method_id is distinct from 'mercadopago'
  or admin_visible_at is null
  or (payment_status = 'approved'
      and financial_status = any (array['payment_confirmed','cancellation_requested','refund_pending','refunded','refund_rejected'])
      and payment_confirmed_at is not null and payment_id is not null)
  or (payment_status = any (array['refunded','charged_back'])
      and payment_confirmed_at is not null and payment_id is not null)
  or (payment_status = any (array['approved_amount_mismatch','approved_currency_mismatch',
        'approved_stock_conflict','approved_after_cancellation'])
      and payment_id is not null));

-- 2. Recepción e inspección (una por pedido) -----------------------------------------
create table public.order_return_inspections (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.ordenes(id) on delete restrict,
  physical_state text not null check (physical_state in
    ('received_ok','not_received','damaged','incomplete','wrong_product')),
  decision text not null check (decision in ('approved','rejected')),
  reason text,
  customer_message text,
  amount numeric(14,2) not null check (amount > 0),
  credit_note_required boolean not null,
  inspected_by uuid not null references public.profiles(id),
  inspected_at timestamptz not null default now(),
  constraint order_return_inspections_received check (decision = 'rejected' or physical_state <> 'not_received'),
  constraint order_return_inspections_reason check (
    decision = 'approved' or length(btrim(coalesce(reason, ''))) between 10 and 600),
  constraint order_return_inspections_customer_message check (
    customer_message is null or length(btrim(customer_message)) between 1 and 300)
);
comment on table public.order_return_inspections is
  'Recepción física y decisión de dinero de una cancelación ya despachada. Inmutable: una sola por pedido.';
alter table public.order_return_inspections enable row level security;
revoke all on public.order_return_inspections from public, anon, authenticated;
grant select, insert on public.order_return_inspections to service_role;

create or replace function public.order_return_money_decision(p_order_id bigint)
returns text language sql stable security definer
set search_path = pg_catalog, public, pg_temp as $$
  select decision from public.order_return_inspections where order_id = p_order_id
$$;
revoke all on function public.order_return_money_decision(bigint) from public, anon, authenticated;
grant execute on function public.order_return_money_decision(bigint) to service_role;

create or replace function public.record_order_return_inspection(
  p_order_id bigint, p_actor_id uuid, p_physical_state text, p_decision text,
  p_reason text, p_customer_message text)
returns public.order_return_inspections
language plpgsql security definer
set search_path = pg_catalog, public, pg_temp as $$
declare
  v_order public.ordenes%rowtype;
  v_row public.order_return_inspections%rowtype;
  v_amount numeric;
  v_reason text := nullif(btrim(coalesce(p_reason, '')), '');
  v_message text := nullif(btrim(coalesce(p_customer_message, '')), '');
begin
  if auth.role() is distinct from 'service_role'
     or not exists (select 1 from public.profiles where id = p_actor_id and rol in ('admin','super_admin')) then
    raise exception 'FINANCIAL_FORBIDDEN';
  end if;
  if p_physical_state not in ('received_ok','not_received','damaged','incomplete','wrong_product')
     or p_decision not in ('approved','rejected') then
    raise exception 'RETURN_INSPECTION_INVALID';
  end if;
  select * into v_order from public.ordenes where id = p_order_id for update;
  if not found then raise exception 'FINANCIAL_ORDER_NOT_FOUND'; end if;

  -- Reintento / refresh: la misma decisión devuelve la registrada; otra distinta nunca.
  select * into v_row from public.order_return_inspections where order_id = p_order_id;
  if found then
    if v_row.physical_state <> p_physical_state or v_row.decision <> p_decision then
      raise exception 'RETURN_INSPECTION_CONFLICT';
    end if;
    return v_row;
  end if;

  if v_order.estado is distinct from 'cancelado' or v_order.financial_status is distinct from 'refund_pending' then
    raise exception 'FINANCIAL_NOT_PENDING';
  end if;
  -- Sólo devoluciones posteriores al despacho: una cancelación previa no se inspecciona.
  if not public.order_dispatch_cutoff_reached(v_order) then
    raise exception 'RETURN_INSPECTION_NOT_APPLICABLE';
  end if;
  if p_decision = 'approved' and p_physical_state = 'not_received' then
    raise exception 'RETURN_NOT_RECEIVED';
  end if;
  if p_decision = 'rejected' and length(coalesce(v_reason, '')) not between 10 and 600 then
    raise exception 'RETURN_REJECTION_REASON_REQUIRED';
  end if;
  if exists (select 1 from public.order_financial_resolutions where order_id = p_order_id)
     or exists (select 1 from public.order_refund_proofs where order_id = p_order_id)
     or exists (select 1 from public.mercadopago_order_refunds where order_id = p_order_id
                and status in ('processing','needs_reconciliation','confirmed')) then
    raise exception 'FINANCIAL_ALREADY_MOVING';
  end if;
  v_amount := coalesce(nullif(v_order.payment_confirmed_amount, 0), nullif(v_order.external_amount_due, 0));
  if v_amount is null or v_amount <= 0 then raise exception 'FINANCIAL_AMOUNT_INVALID'; end if;

  insert into public.order_return_inspections(order_id, physical_state, decision, reason, customer_message,
      amount, credit_note_required, inspected_by)
    values (p_order_id, p_physical_state, p_decision, v_reason, left(v_message, 300), v_amount,
      coalesce(v_order.credit_note_required, false), p_actor_id)
    returning * into v_row;

  if p_decision = 'rejected' then
    -- Cierra el dinero sin moverlo: ninguna RPC de saldo/reintegro opera fuera de refund_pending.
    update public.ordenes set financial_status = 'refund_rejected' where id = p_order_id;
    if v_order.usuario_id is not null then
      insert into public.customer_notifications(user_id, type, title, body, action_url, order_id, source_key)
        values (v_order.usuario_id, 'order_refund_rejected', 'Devolución revisada',
          'Revisamos la devolución de tu pedido BX-' || (1000 + p_order_id) || ' y no pudimos aprobar el reintegro.'
            || coalesce(' ' || left(v_message, 300), ''),
          '/cuenta/compras/' || p_order_id, p_order_id, 'order:' || p_order_id || ':refund-rejected')
        on conflict (source_key) do nothing;
    end if;
  end if;

  insert into public.order_audit_events(order_id, actor_type, actor_id, action, previous_status, new_status, metadata)
    values (p_order_id, 'admin', p_actor_id, 'return_inspection_recorded', v_order.financial_status,
      case when p_decision = 'rejected' then 'refund_rejected' else v_order.financial_status end,
      jsonb_build_object('inspectionId', v_row.id, 'physicalState', p_physical_state, 'decision', p_decision,
        'reason', v_reason, 'customerMessage', v_row.customer_message, 'amount', v_amount,
        'creditNoteRequired', v_row.credit_note_required, 'invoiceCae', v_order.invoice_cae));
  return v_row;
end $$;
revoke all on function public.record_order_return_inspection(bigint, uuid, text, text, text, text)
  from public, anon, authenticated;
grant execute on function public.record_order_return_inspection(bigint, uuid, text, text, text, text)
  to service_role;

-- 3. Ningún camino mueve dinero sin la decisión ---------------------------------------
-- Rechazada: ni saldo, ni reintegro, ni NC con dinero. Cancelación ya despachada
-- sin aprobación: tampoco (cubre también los flujos anteriores al orquestador).
create or replace function public.guard_return_money_decision()
returns trigger language plpgsql security definer
set search_path = pg_catalog, public, pg_temp as $$
declare v_order public.ordenes%rowtype; v_decision text;
begin
  -- IF anidados: cada tabla sólo evalúa sus propias columnas.
  if tg_table_name = 'order_credit_notes' then
    if coalesce(new.destination, 'none') not in ('external_refund','customer_balance') then return new; end if;
  elsif tg_table_name = 'customer_credit_movements' then
    if new.order_id is null or coalesce(new.movement_type, '') not in ('credit','reversal','adjustment') then return new; end if;
  end if;
  select * into v_order from public.ordenes where id = new.order_id;
  if not found then return new; end if;
  v_decision := public.order_return_money_decision(new.order_id);
  if v_decision = 'rejected' or v_order.financial_status = 'refund_rejected' then
    raise exception 'RETURN_MONEY_REJECTED';
  end if;
  -- El saldo usado en la compra (reversión al cancelar) sigue sus propias reglas.
  if tg_table_name <> 'customer_credit_movements'
     and v_order.estado = 'cancelado' and v_order.financial_status = 'refund_pending'
     and public.order_dispatch_cutoff_reached(v_order) and v_decision is distinct from 'approved' then
    raise exception 'RETURN_INSPECTION_REQUIRED';
  end if;
  return new;
end $$;
revoke all on function public.guard_return_money_decision() from public, anon, authenticated;

create trigger guard_return_money_decision before insert on public.order_financial_resolutions
  for each row execute function public.guard_return_money_decision();
create trigger guard_return_money_decision before insert on public.order_refund_proofs
  for each row execute function public.guard_return_money_decision();
create trigger guard_return_money_decision before insert or update of status on public.mercadopago_order_refunds
  for each row when (new.status in ('requested','processing'))
  execute function public.guard_return_money_decision();
create trigger guard_return_money_decision before insert on public.order_credit_notes
  for each row execute function public.guard_return_money_decision();
create trigger guard_return_money_decision before insert on public.customer_credit_movements
  for each row execute function public.guard_return_money_decision();

-- 4. Resolución financiera ------------------------------------------------------------
-- Igual que 20261023100000 salvo: un pedido ya despachado (corte canónico) sólo
-- se reserva con la devolución aprobada; con ella, el saldo BEYONIX vuelve a
-- estar disponible (la mercadería ya volvió y se inspeccionó).
create or replace function public.reserve_order_financial_resolution(
  p_order_id bigint,p_actor_id uuid,p_choice text
) returns public.order_financial_resolutions
language plpgsql security definer
set search_path=pg_catalog,public,pg_temp as $$
declare v_order public.ordenes%rowtype; v_row public.order_financial_resolutions%rowtype;
  v_amount numeric; v_paid_amount numeric; v_note_amount numeric; v_role text; v_return_approved boolean;
begin
  if auth.role() is distinct from 'service_role' then raise exception 'FINANCIAL_FORBIDDEN'; end if;
  select rol into v_role from public.profiles where id=p_actor_id;
  if coalesce(v_role,'') not in ('admin','super_admin') then raise exception 'FINANCIAL_FORBIDDEN'; end if;
  if p_choice not in ('beyonix_credit','mercadopago_refund','manual_refund') then raise exception 'FINANCIAL_INVALID_CHOICE'; end if;
  select * into v_order from public.ordenes where id=p_order_id for update;
  if not found then raise exception 'FINANCIAL_ORDER_NOT_FOUND'; end if;
  select * into v_row from public.order_financial_resolutions where order_id=p_order_id for update;
  if found then
    if v_row.choice<>p_choice then raise exception 'FINANCIAL_CHOICE_CONFLICT'; end if;
    return v_row;
  end if;
  if v_order.financial_status is distinct from 'refund_pending'
     or v_order.paid_at is null or v_order.payment_status not in ('approved','confirmed','confirmado') then
    raise exception 'FINANCIAL_NOT_PENDING';
  end if;
  v_return_approved := coalesce(public.order_return_money_decision(p_order_id) = 'approved', false);
  if public.order_dispatch_cutoff_reached(v_order) and not v_return_approved then
    raise exception 'FINANCIAL_RETURN_INSPECTION_REQUIRED';
  end if;
  -- Con corte de preparación, saldo BEYONIX sólo si la mercadería ya volvió
  -- (cancelación con pickeo resuelta por escaneo, o devolución inspeccionada y
  -- aprobada) y el pedido no sigue en un Bulto.
  if p_choice='beyonix_credit' and not v_return_approved and public.order_was_prepared_for_dispatch(p_order_id)
     and (not public.order_cancelled_after_picking(p_order_id)
          or public.order_has_active_stock_hold(p_order_id)
          or exists (select 1 from public.dispatch_batch_items i
                     where i.order_id=p_order_id and i.removed_at is null)) then
    raise exception 'FINANCIAL_PREPARED_MANUAL_ONLY';
  end if;
  if p_choice='mercadopago_refund' and v_order.payment_method_id is distinct from 'mercadopago' then
    raise exception 'FINANCIAL_INVALID_PAYMENT_METHOD';
  end if;
  if p_choice='beyonix_credit' and v_order.usuario_id is null then raise exception 'FINANCIAL_NO_ACCOUNT'; end if;
  v_paid_amount := coalesce(nullif(v_order.payment_confirmed_amount,0),nullif(v_order.external_amount_due,0));
  if v_paid_amount is null or v_paid_amount<=0 then raise exception 'FINANCIAL_AMOUNT_INVALID'; end if;
  select coalesce(sum(coalesce(external_amount,total_amount)),0) into v_note_amount from public.order_credit_notes
    where order_id=p_order_id and status='authorized' and destination='external_refund'
      and settlement_status is distinct from 'completado' and cae is not null;
  if v_note_amount>v_paid_amount then raise exception 'FINANCIAL_AMOUNT_INVALID'; end if;
  if p_choice='manual_refund' and v_order.payment_method_id is distinct from 'transferencia' and
     not (v_order.payment_method_id='mercadopago' and
       (public.order_was_prepared_for_dispatch(p_order_id) or v_return_approved
        or (v_note_amount>0 and v_note_amount<v_paid_amount))) then
    raise exception 'FINANCIAL_INVALID_PAYMENT_METHOD';
  end if;
  v_amount := case when p_choice='manual_refund' and v_note_amount>0 then v_note_amount else v_paid_amount end;
  if p_choice='mercadopago_refund' and (nullif(btrim(v_order.payment_id),'') is null
      or (v_note_amount>0 and v_note_amount<>v_paid_amount)) then
    raise exception 'FINANCIAL_MP_INELIGIBLE';
  end if;
  if p_choice='mercadopago_refund' and public.order_dispatch_cutoff_reached(v_order) then
    raise exception 'FINANCIAL_RETURN_REQUIRED';
  end if;
  if p_choice='beyonix_credit' and exists(select 1 from public.order_credit_notes
       where order_id=p_order_id and status='authorized' and destination='customer_balance' and cae is not null) then
    raise exception 'FINANCIAL_ALREADY_MOVING';
  end if;
  if exists(select 1 from public.order_refund_proofs where order_id=p_order_id) or
     exists(select 1 from public.mercadopago_order_refunds where order_id=p_order_id and status in ('confirmed','processing','needs_reconciliation')) then
    raise exception 'FINANCIAL_ALREADY_MOVING';
  end if;
  insert into public.order_financial_resolutions(order_id,choice,amount,selected_by)
    values(p_order_id,p_choice,v_amount,p_actor_id) returning * into v_row;
  insert into public.order_audit_events(order_id,actor_type,actor_id,action,previous_status,new_status,metadata)
    values(p_order_id,'admin',p_actor_id,'financial_resolution_selected',v_order.financial_status,'reserved',
      jsonb_build_object('choice',p_choice,'amount',v_amount,'resolutionId',v_row.id,
        'preparedCut',public.order_was_prepared_for_dispatch(p_order_id),'returnApproved',v_return_approved));
  return v_row;
end;
$$;
revoke all on function public.reserve_order_financial_resolution(bigint,uuid,text) from public,anon,authenticated;
grant execute on function public.reserve_order_financial_resolution(bigint,uuid,text) to service_role;

-- 5. NC de la cancelación ya despachada -----------------------------------------------
-- Igual que 20261023110000 más: la cancelación de Super Admin de una venta ya
-- entregada a Andreani autoriza la NC de cancelación una vez aprobada la devolución.
create or replace function public.order_has_admin_direct_cancellation(p_order_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.order_audit_events e
    where e.order_id = p_order_id
      and e.actor_type = 'admin'
      and (
        (e.action = 'order_cancelled_refund_pending'
          and e.metadata->>'source' = 'admin_direct_cancellation')
        or (e.action = 'order_force_cancelled_by_super_admin'
          and e.metadata->>'newEstado' = 'cancelado'
          and (coalesce(e.metadata->'stock'->>'dispatchedRetention', 'false') <> 'true'
               or exists (select 1 from public.order_return_inspections i
                          where i.order_id = p_order_id and i.decision = 'approved')))
      )
  )
$$;

revoke all on function public.order_has_admin_direct_cancellation(bigint) from public, anon, authenticated;
grant execute on function public.order_has_admin_direct_cancellation(bigint) to service_role;
