-- 3. Efecto de stock y huella --------------------------------------------------

create or replace function public.external_sale_consumes_stock(
  p_stock_effect text,
  p_status text,
  p_reversal_kind text,
  p_return_condition text
)
returns boolean
language sql
immutable
set search_path = public
as $$
  select coalesce(
    p_stock_effect = 'consume'
    and (
      p_status <> 'reversed'
      or (p_reversal_kind = 'return' and p_return_condition = 'damaged')
    ),
    false
  );
$$;

create or replace function public.external_sale_content_hash(
  p_sale_date date,
  p_sku text,
  p_customer_name text,
  p_quantity integer,
  p_amount numeric
)
returns text
language sql
immutable
set search_path = public
as $$
  select md5(concat_ws(
    chr(31),
    coalesce(p_sale_date::text, ''),
    coalesce(public.normalized_catalog_sku(p_sku), ''),
    lower(regexp_replace(btrim(coalesce(p_customer_name, '')), '\s+', ' ', 'g')),
    coalesce(p_quantity::text, ''),
    coalesce(round(p_amount, 2)::text, '')
  ));
$$;

create or replace function public.set_external_sale_content_hash()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.content_hash := public.external_sale_content_hash(
    new.sale_date, new.sku, new.customer_name, new.quantity, new.gross_amount
  );
  return new;
end;
$$;

create trigger set_external_sale_content_hash
before insert or update of sale_date, sku, customer_name, quantity, gross_amount
on public.external_sales
for each row execute function public.set_external_sale_content_hash();

