  'inventory_stock_adjustments'::text,
  adjustments.created_at, adjustments.created_by, 'admin_stock_adjustment'::text,
  coalesce(adjustments.idempotency_key, 'stock-adjustment:' || adjustments.id::text),
  adjustments.reason
from public.inventory_stock_adjustments adjustments
where adjustments.quantity_delta <> 0;

-- Recalcula stock sólo cuando la fila cambia lo que aporta al libro: una
-- tanda histórica (stock_effect = none) no dispara un recálculo por fila.
create or replace function public.refresh_inventory_from_external_sale()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_old_consumes boolean := false;
  v_new_consumes boolean := false;
  v_old_product_id bigint;
begin
  if tg_op <> 'INSERT' then
    v_old_product_id := old.product_id;
    v_old_consumes := old.product_id is not null and public.external_sale_consumes_stock(
      old.stock_effect, old.status, old.reversal_kind, old.return_condition
    );
  end if;
  if tg_op <> 'DELETE' then
    v_new_consumes := new.product_id is not null and public.external_sale_consumes_stock(
      new.stock_effect, new.status, new.reversal_kind, new.return_condition
    );
  end if;

  if tg_op = 'UPDATE'
     and v_old_consumes = v_new_consumes
     and old.product_id is not distinct from new.product_id
     and old.variant_id is not distinct from new.variant_id
     and old.quantity = new.quantity
     and old.sale_date = new.sale_date then
    return new;
  end if;

  if v_old_consumes then
    perform public.refresh_inventory_stock(v_old_product_id);
  end if;
  if v_new_consumes and (not v_old_consumes or new.product_id is distinct from v_old_product_id) then
    perform public.refresh_inventory_stock(new.product_id);
  end if;

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

drop trigger if exists refresh_inventory_after_external_sale on public.external_sales;
create trigger refresh_inventory_after_external_sale
after insert or update or delete on public.external_sales
for each row execute function public.refresh_inventory_from_external_sale();

-- 5. Guardas de historial y camino de escritura -----------------------------------
-- Las ventas externas sólo se crean, editan y anulan por las RPC de esta
-- migración, que marcan la transacción con beyonix.external_sale_write = 'rpc'.
-- Fuera de ellas (endpoints viejos, SQL suelto) sólo se admite el cambio de
-- vínculo de catálogo que hacen fusión/borrado forzado de productos y el
-- ON DELETE SET NULL de productos.

create or replace function public.external_sale_rpc_write()
returns boolean
language sql
stable
set search_path = public
as $$
  select coalesce(current_setting('beyonix.external_sale_write', true), '') = 'rpc';
$$;

create or replace function public.guard_external_sale_insert()
returns trigger language plpgsql set search_path = public as $$
begin
  if not public.external_sale_rpc_write() then
    raise exception 'EXTERNAL_SALE_WRITE_PATH_FORBIDDEN: las ventas externas se cargan desde Admin > Ventas externas.';
  end if;
  return new;
end;
$$;

drop trigger if exists guard_external_sale_insert on public.external_sales;
create trigger guard_external_sale_insert
before insert on public.external_sales
for each row execute function public.guard_external_sale_insert();

create or replace function public.guard_external_sale_history()
returns trigger language plpgsql set search_path = public as $$
begin
  if not public.external_sale_rpc_write()
     and (to_jsonb(new) - array['product_id', 'variant_id', 'updated_at'])
         is distinct from (to_jsonb(old) - array['product_id', 'variant_id', 'updated_at']) then
    raise exception 'EXTERNAL_SALE_WRITE_PATH_FORBIDDEN: las ventas externas se editan y anulan desde Admin > Ventas externas.';
  end if;
  if old.status = 'reversed' then
    -- Existing super-admin force-delete RPCs detach catalog references while
    -- preserving the sale. Allow only that backend operation, never an edit.
    if auth.role() is distinct from 'service_role'
       or (to_jsonb(new) - array['product_id', 'variant_id', 'updated_at'])
          is distinct from (to_jsonb(old) - array['product_id', 'variant_id', 'updated_at'])
       or (new.product_id is not null and new.product_id is distinct from old.product_id)
       or (new.variant_id is not null and new.variant_id is distinct from old.variant_id)
       or (new.product_id is not distinct from old.product_id and new.variant_id is not distinct from old.variant_id) then
      raise exception 'EXTERNAL_SALE_ALREADY_REVERSED';
    end if;
  end if;
  if new.creation_idempotency_key is distinct from old.creation_idempotency_key
     or new.creation_request is distinct from old.creation_request then
    raise exception 'EXTERNAL_SALE_CREATION_IMMUTABLE';
  end if;
  -- Pasar de histórica a nueva (o al revés) cambia el stock: nunca por edición.
  if new.stock_effect is distinct from old.stock_effect then
    raise exception 'EXTERNAL_SALE_STOCK_EFFECT_IMMUTABLE';
  end if;
  if (new.sale_number, new.origin, new.import_batch_id, new.source_row_number, new.source_values)
     is distinct from
     (old.sale_number, old.origin, old.import_batch_id, old.source_row_number, old.source_values) then
    raise exception 'EXTERNAL_SALE_SOURCE_IMMUTABLE';
  end if;
  return new;
end;
$$;

-- Auditoría por fila de external_sales. Reemplaza al trigger genérico
-- audit_log_change sólo en esta tabla (la función global no cambia): dentro
-- de las RPC ya se escribe un evento explícito con actor, alcance y motivo,
-- así que no se duplica; fuera de ellas (re-vinculación de catálogo) se
-- registra como siempre, sin copiar source_values ni creation_request en
-- cada UPDATE (son inmutables y quedan en la fila).
create or replace function public.audit_external_sale_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor_user_id uuid := auth.uid();
  v_actor_email text;
begin
  if public.external_sale_rpc_write() or current_setting('app.audit_skip', true) = 'true' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;
  select profiles.email into v_actor_email from public.profiles where profiles.id = v_actor_user_id;
  insert into public.audit_logs (
    table_name, action, record_id, actor_user_id, actor_email, before_data, after_data
  ) values (
    tg_table_name,
    tg_op,
    case when tg_op = 'DELETE' then old.id::text else new.id::text end,
    v_actor_user_id,
    coalesce(v_actor_email, auth.jwt() ->> 'email'),
    case
      when tg_op = 'DELETE' then to_jsonb(old)
      when tg_op = 'UPDATE' then to_jsonb(old) - array['source_values', 'creation_request']
    end,
    case
      when tg_op = 'INSERT' then to_jsonb(new)
      when tg_op = 'UPDATE' then to_jsonb(new) - array['source_values', 'creation_request']
    end
  );
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

drop trigger if exists external_sales_audit_log_trigger on public.external_sales;
create trigger external_sales_audit_log_trigger
after insert or update or delete on public.external_sales
for each row execute function public.audit_external_sale_change();

