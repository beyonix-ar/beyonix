-- Ventas externas: importación por tandas (Históricas / Nuevas), efecto de
-- stock explícito, anulación por error de carga vs devolución real, edición
-- transaccional con versión y "deshacer tanda".
--
-- external_sales sigue siendo la única entidad de venta externa (una fila por
-- producto vendido). No se crean órdenes, pagos ni eventos de analítica.
--
-- Stock: el inventario sigue siendo una proyección de inventory_movements. Una
-- venta externa descuenta stock sólo si external_sale_consumes_stock() es
-- verdadero (stock_effect = 'consume' y la venta no fue anulada, salvo una
-- devolución con el producto dañado, que nunca vuelve al stock vendible).
-- Las filas existentes quedan con stock_effect = 'consume': ya descontaban.

begin;

-- 1. Tandas de importación ----------------------------------------------------

create table public.external_sale_import_batches (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  source text not null,
  file_name text,
  content_hash text not null,
  request_hash text not null,
  stock_mode text not null,
  rows_read integer not null,
  rows_valid integer not null,
  rows_imported integer not null,
  status text not null default 'completed',
  idempotency_key text not null,
  reverted_at timestamptz,
  reverted_by uuid references auth.users(id) on delete set null,
  revert_reason text,
  constraint external_sale_import_batches_source_check check (source in ('paste', 'file')),
  constraint external_sale_import_batches_file_check check (
    (source = 'paste' and file_name is null)
    or (source = 'file' and file_name is not null and length(btrim(file_name)) between 1 and 255)
  ),
  constraint external_sale_import_batches_hash_check check (
    content_hash ~ '^[0-9a-f]{64}$' and request_hash ~ '^[0-9a-f]{64}$'
  ),
  constraint external_sale_import_batches_stock_mode_check check (stock_mode in ('none', 'consume')),
  constraint external_sale_import_batches_counts_check check (
    rows_imported >= 1 and rows_imported <= rows_valid and rows_valid <= rows_read
  ),
  constraint external_sale_import_batches_key_check check (length(idempotency_key) between 8 and 240),
  constraint external_sale_import_batches_status_check check (
    (status = 'completed' and reverted_at is null and reverted_by is null and revert_reason is null)
    or (status = 'reverted' and reverted_at is not null and revert_reason is not null
        and length(btrim(revert_reason)) >= 10)
  )
);

create unique index external_sale_import_batches_key_uidx
  on public.external_sale_import_batches(idempotency_key);
create index external_sale_import_batches_created_at_idx
  on public.external_sale_import_batches(created_at desc);
create index external_sale_import_batches_content_hash_idx
  on public.external_sale_import_batches(content_hash);

alter table public.external_sale_import_batches enable row level security;
revoke all on public.external_sale_import_batches from public, anon, authenticated;
grant all on public.external_sale_import_batches to service_role;

comment on table public.external_sale_import_batches is
  'Una fila por tanda de ventas externas pegada o importada: quién, cuándo, modo de stock (none = histórica, consume = nueva) y su reversión.';

