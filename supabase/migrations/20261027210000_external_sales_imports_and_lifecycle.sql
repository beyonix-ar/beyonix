$$;

create or replace function public.external_sale_resolve_sku(p_sku text)
returns table (
  resolution text,
  product_id bigint,
  variant_id bigint,
  product_name text,
  variant_name text
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_sku text := public.normalized_catalog_sku(p_sku);
  v_registry record;
  v_product record;
  v_variant record;
begin
  if v_sku is null then
    return query select 'missing'::text, null::bigint, null::bigint, null::text, null::text;
    return;
  end if;

  select registry.product_id, registry.variant_id, registry.conditioned_stock_id
  into v_registry
  from public.catalog_sku_registry registry
  where registry.normalized_sku = v_sku;

  if found then
    if v_registry.conditioned_stock_id is not null then
      return query select 'conditioned'::text, null::bigint, null::bigint, null::text, null::text;
      return;
    end if;
    if v_registry.variant_id is not null then
      select variants.id, variants.producto_id, variants.nombre, variants.activo
      into v_variant
      from public.producto_variantes variants
      where variants.id = v_registry.variant_id;
      select products.id, products.nombre, products.activo
      into v_product
      from public.productos products
      where products.id = v_variant.producto_id;
      return query select
        case when v_product.activo and v_variant.activo then 'ok' else 'archived' end,
        v_product.id, v_variant.id, v_product.nombre, v_variant.nombre;
      return;
    end if;

    select products.id, products.nombre, products.activo
    into v_product
    from public.productos products
    where products.id = v_registry.product_id;
    if exists (select 1 from public.producto_variantes variants where variants.producto_id = v_product.id) then
      return query select 'needs_variant'::text, v_product.id, null::bigint, v_product.nombre, null::text;
      return;
    end if;
    return query select
      case when v_product.activo then 'ok' else 'archived' end,
      v_product.id, null::bigint, v_product.nombre, null::text;
    return;
  end if;

  -- SKU que ya no está en el catálogo pero existe en compras o ventas
  -- externas anteriores: sólo admisible como venta histórica (sin stock).
  if exists (
    select 1 from public.product_cost_entries entries
    where public.normalized_catalog_sku(entries.sku) = v_sku
  ) or exists (
    select 1 from public.external_sales sales
    where public.normalized_catalog_sku(sales.sku) = v_sku
  ) then
    return query select 'historical'::text, null::bigint, null::bigint, null::text, null::text;
    return;
  end if;

  return query select 'missing'::text, null::bigint, null::bigint, null::text, null::text;
end;
$$;

-- Unidades vendibles de un artículo: stock derivado menos reservas activas
-- del checkout web (misma regla que available_stock_for_session).
create or replace function public.external_sale_available_units(
  p_product_id bigint,
  p_variant_id bigint
)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select (
    case
      when p_variant_id is null then
        (select coalesce(products.stock, 0) from public.productos products where products.id = p_product_id)
      else
        (select coalesce(variants.stock, 0) from public.producto_variantes variants
         where variants.id = p_variant_id and variants.producto_id = p_product_id)
    end
    - coalesce((
      select sum(reservations.quantity)
      from public.stock_reservations reservations
      where reservations.product_id = p_product_id
        and reservations.variant_id is not distinct from p_variant_id
        and reservations.conditioned_stock_id is null
        and reservations.expires_at > now()
    ), 0)
  )::integer;
$$;

-- Valida y normaliza una venta. p_resolve_sku = false conserva el producto
-- vinculado (edición sin cambio de SKU: un SKU que salió del catálogo no
-- impide corregir otros datos).
create or replace function public.external_sale_prepare(
  p_input jsonb,
  p_stock_effect text,
  p_resolve_sku boolean,
  p_label text default null
)
returns public.external_sales
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v public.external_sales%rowtype;
  v_prefix text := case when p_label is null then '' else p_label || ': ' end;
  v_today date := (now() at time zone 'America/Argentina/Buenos_Aires')::date;
  v_resolved record;
  v_catalog_name text;
begin
  if p_input is null or jsonb_typeof(p_input) <> 'object' then
    raise exception 'EXTERNAL_SALE_INVALID: %los datos de la venta no son válidos.', v_prefix;
  end if;
  if p_stock_effect is null or p_stock_effect not in ('none', 'consume') then
    raise exception 'EXTERNAL_SALE_INVALID: %elegí si la venta es histórica o nueva.', v_prefix;
  end if;

  begin
    v.sale_date := (p_input ->> 'sale_date')::date;
    v.quantity := (p_input ->> 'quantity')::integer;
    v.gross_amount := round((p_input ->> 'gross_amount')::numeric, 2);
    v.shipping_amount := round(coalesce(nullif(p_input ->> 'shipping_amount', '')::numeric, 0), 2);
    v.declared_profit := round(nullif(p_input ->> 'declared_profit', '')::numeric, 2);
    v.unit_cost := round(coalesce(nullif(p_input ->> 'unit_cost', '')::numeric, 0), 2);
    v.fee_type := coalesce(nullif(p_input ->> 'fee_type', ''), 'amount');
    v.fee_value := round(coalesce(nullif(p_input ->> 'fee_value', '')::numeric, 0), 2);
    v.other_expense_amount := round(coalesce(nullif(p_input ->> 'other_expense_amount', '')::numeric, 0), 2);
    v.product_id := nullif(p_input ->> 'product_id', '')::bigint;
    v.variant_id := nullif(p_input ->> 'variant_id', '')::bigint;
  exception when others then
    raise exception 'EXTERNAL_SALE_INVALID: %la fecha, la cantidad o algún importe no tienen un formato válido.', v_prefix;
  end;

  if v.sale_date is null or v.sale_date < date '2000-01-01' or v.sale_date > v_today then
    raise exception 'EXTERNAL_SALE_INVALID: %la fecha de venta debe ser válida y no puede ser futura.', v_prefix;
  end if;
  if v.quantity is null or v.quantity < 1 or v.quantity > 100000 then
    raise exception 'EXTERNAL_SALE_INVALID: %la cantidad debe ser un entero mayor a cero.', v_prefix;
  end if;
  if v.gross_amount is null or v.gross_amount < 0 then
    raise exception 'EXTERNAL_SALE_INVALID: %el precio final debe ser un importe mayor o igual a cero.', v_prefix;
  end if;
  if v.shipping_amount < 0 or v.unit_cost < 0 or v.fee_value < 0 or v.other_expense_amount < 0
     or v.fee_type not in ('amount', 'percent') or (v.fee_type = 'percent' and v.fee_value > 100) then
    raise exception 'EXTERNAL_SALE_INVALID: %el envío y los gastos no pueden ser negativos.', v_prefix;
  end if;

  v.status := coalesce(nullif(p_input ->> 'status', ''), 'completed');
  if v.status not in ('completed', 'delivered') then
    raise exception 'EXTERNAL_SALE_INVALID: %el estado debe ser Confirmada o Entregada.', v_prefix;
  end if;
  v.channel := nullif(p_input ->> 'channel', '');
  if v.channel is not null and v.channel not in ('whatsapp', 'instagram', 'direct', 'other') then
    raise exception 'EXTERNAL_SALE_INVALID: %el canal no es válido.', v_prefix;
  end if;
  v.payment_method_code := nullif(p_input ->> 'payment_method_code', '');
  if v.payment_method_code is not null and v.payment_method_code not in (
    'transfer', 'cash', 'mercadopago', 'mercadopago_qr', 'card', 'other'
  ) then
    raise exception 'EXTERNAL_SALE_INVALID: %el medio de pago no es válido.', v_prefix;
  end if;

  v.customer_name := left(nullif(btrim(p_input ->> 'customer_name'), ''), 180);
  v.channel_label := left(nullif(btrim(p_input ->> 'channel_label'), ''), 80);
  v.payment_method := left(nullif(btrim(p_input ->> 'payment_method'), ''), 100);
  v.notes := left(nullif(btrim(p_input ->> 'notes'), ''), 1000);
  v.reference := left(nullif(btrim(p_input ->> 'reference'), ''), 160);
  v.sku := left(nullif(btrim(p_input ->> 'sku'), ''), 120);

  if p_resolve_sku then
    if v.sku is null then
      v.variant_id := case when v.product_id is null then null else v.variant_id end;
      if v.product_id is null then
        raise exception 'EXTERNAL_SALE_INVALID: %indicá el SKU del producto vendido.', v_prefix;
      end if;
      select products.nombre || coalesce(' · ' || variants.nombre, '')
      into v_catalog_name
      from public.productos products
      left join public.producto_variantes variants
        on variants.id = v.variant_id and variants.producto_id = products.id
      where products.id = v.product_id;
      if not found then
        raise exception 'EXTERNAL_SALE_INVALID: %el producto seleccionado ya no existe.', v_prefix;
      end if;
    else
      select * into v_resolved from public.external_sale_resolve_sku(v.sku);
      if v_resolved.resolution in ('ok', 'archived') then
        v.product_id := v_resolved.product_id;
        v.variant_id := v_resolved.variant_id;
        v_catalog_name := v_resolved.product_name || coalesce(' · ' || v_resolved.variant_name, '');
      elsif v_resolved.resolution in ('historical', 'missing') then
        -- SKU histórico sin vínculo con el catálogo actual (ya no existe o
        -- sólo figura en el Excel): admisible únicamente como histórica,
        -- que no mueve stock. Se conservan SKU y nombre del Excel.
        if p_stock_effect = 'consume' then
          raise exception 'EXTERNAL_SALE_INVALID: %el SKU % no está en el catálogo actual: una venta nueva necesita un producto válido. Sólo puede cargarse como venta histórica.', v_prefix, v.sku;
        end if;
        v.product_id := null;
        v.variant_id := null;
      elsif v_resolved.resolution = 'needs_variant' then
        raise exception 'EXTERNAL_SALE_INVALID: %el SKU % es de un producto con variantes: usá el SKU de la variante vendida.', v_prefix, v.sku;
      else
        raise exception 'EXTERNAL_SALE_INVALID: %el SKU % es de stock reacondicionado y no se admite en ventas externas.', v_prefix, v.sku;
      end if;
    end if;
  end if;

  v.product_name := left(coalesce(nullif(btrim(p_input ->> 'product_name'), ''), v_catalog_name), 240);
  if v.product_name is null then
    raise exception 'EXTERNAL_SALE_INVALID: %falta el nombre del producto.', v_prefix;
  end if;
  -- Sólo al elegir el artículo: una venta anterior sin producto vinculado
  -- (artículo no catalogado) sigue siendo editable sin cambiar su SKU.
  if p_resolve_sku and p_stock_effect = 'consume' and v.product_id is null then
    raise exception 'EXTERNAL_SALE_INVALID: %una venta nueva necesita un producto del catálogo para descontar stock.', v_prefix;
  end if;

  v.stock_effect := p_stock_effect;
  v.unit_price := round(v.gross_amount / v.quantity, 2);
  v.fee_amount := case
    when v.fee_type = 'percent' then round(v.gross_amount * v.fee_value / 100, 2)
    else v.fee_value
  end;
  v.net_amount := v.gross_amount - v.quantity * v.unit_cost - v.fee_amount
    - v.shipping_amount - v.other_expense_amount;
  return v;
end;
$$;

create or replace function public.external_sale_lock_products(p_product_ids bigint[])
returns void
language plpgsql
set search_path = public
as $$
declare
  v_product_id bigint;
begin
  for v_product_id in
    select distinct ids.product_id
    from unnest(p_product_ids) ids(product_id)
    where ids.product_id is not null
    order by ids.product_id
  loop
    perform pg_advisory_xact_lock(93000, v_product_id::integer);
  end loop;
end;
$$;

-- Serializa la comprobación de posibles duplicados entre transacciones
-- concurrentes (dos tandas iguales con claves distintas, o una tanda y un
-- alta manual). Se bloquea por huella (en 256 grupos, para acotar la
-- cantidad de locks de una tanda grande) antes de comprobar y se mantiene
-- hasta el commit: quien llega segundo espera y ve las filas del primero.
-- No es una restricción: "Es una venta distinta" sigue permitiendo
-- registrar ventas iguales. Orden global de locks: idempotencia -> huellas
-- -> productos.
create or replace function public.external_sale_lock_content_hashes(p_hashes text[])
returns void
language plpgsql
set search_path = public
as $$
declare
  v_bucket integer;
begin
  for v_bucket in
    select distinct hashtext(hashes.hash) & 255
    from unnest(p_hashes) hashes(hash)
    where hashes.hash is not null
    order by 1
  loop
    perform pg_advisory_xact_lock(hashtext('external-sale-content'), v_bucket);
  end loop;
end;
$$;

