-- 7. Alta manual ----------------------------------------------------------------------

create or replace function public.create_external_sale_idempotent(
  p_payload jsonb, p_actor_id uuid, p_idempotency_key text
)
returns public.external_sales language plpgsql security definer set search_path = public as $$
declare
  v_sale public.external_sales%rowtype;
  v_input public.external_sales%rowtype;
  v_stock_effect text := p_payload ->> 'stock_effect';
  v_available integer;
begin
  perform public.external_sale_require_admin(p_actor_id);
  if p_idempotency_key is null or length(p_idempotency_key) not between 8 and 240 then
    raise exception 'IDEMPOTENCY_KEY_INVALID';
  end if;
  perform pg_advisory_xact_lock(hashtext('external-sale-create'), hashtext(p_idempotency_key));
  select * into v_sale from public.external_sales where creation_idempotency_key = p_idempotency_key;
  if found then
    if v_sale.creation_request is distinct from p_payload or v_sale.created_by is distinct from p_actor_id then
      raise exception 'IDEMPOTENCY_PAYLOAD_MISMATCH';
    end if;
    return v_sale;
  end if;

  v_input := public.external_sale_prepare(p_payload, v_stock_effect, true);
  -- Una tanda concurrente con el mismo contenido espera a este alta y la ve.
  perform public.external_sale_lock_content_hashes(array[public.external_sale_content_hash(
    v_input.sale_date, v_input.sku, v_input.customer_name, v_input.quantity, v_input.gross_amount
  )]);
  perform public.external_sale_lock_products(array[v_input.product_id]);
  if public.external_sale_consumes_stock(v_input.stock_effect, v_input.status, null, null) then
    v_available := public.external_sale_available_units(v_input.product_id, v_input.variant_id);
    if v_input.quantity > coalesce(v_available, 0) then
      raise exception 'EXTERNAL_SALE_STOCK_UNAVAILABLE: % tiene % unidades disponibles (descontando reservas web) y la venta pide %.',
        coalesce(v_input.sku, v_input.product_name), greatest(coalesce(v_available, 0), 0), v_input.quantity;
    end if;
  end if;

  perform public.external_sale_begin_write(p_actor_id);
  insert into public.external_sales (
    sale_date, product_id, variant_id, product_name, sku, quantity, unit_price, unit_cost,
    gross_amount, fee_type, fee_value, fee_amount, shipping_amount, other_expense_amount,
    net_amount, payment_method, payment_method_code, reference, customer_name, notes,
    channel, channel_label, status, declared_profit, stock_effect, origin,
    created_by, updated_by, creation_idempotency_key, creation_request
  ) values (
    v_input.sale_date, v_input.product_id, v_input.variant_id, v_input.product_name, v_input.sku,
    v_input.quantity, v_input.unit_price, v_input.unit_cost, v_input.gross_amount,
    v_input.fee_type, v_input.fee_value, v_input.fee_amount, v_input.shipping_amount,
    v_input.other_expense_amount, v_input.net_amount, v_input.payment_method,
    v_input.payment_method_code, v_input.reference, v_input.customer_name, v_input.notes,
    v_input.channel, v_input.channel_label, v_input.status, v_input.declared_profit,
    v_input.stock_effect, 'manual', p_actor_id, p_actor_id, p_idempotency_key, p_payload
  ) returning * into v_sale;

  perform public.external_sale_write_audit(
    'INSERT', v_sale.id::text, p_actor_id, null,
    public.external_sale_audit_payload(v_sale) || jsonb_build_object('scope', 'external_sale_create')
  );
  perform public.external_sale_end_write();
  return v_sale;
end;
$$;

-- 8. Edición ----------------------------------------------------------------------------

create or replace function public.update_external_sale(
  p_id uuid,
  p_expected_version integer,
  p_patch jsonb,
  p_actor_id uuid,
  p_reason text default null
)
returns public.external_sales
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old public.external_sales%rowtype;
  v_new public.external_sales%rowtype;
  v_key text;
  v_editable text[] := array[
    'sale_date', 'customer_name', 'channel', 'channel_label', 'sku', 'product_name',
    'quantity', 'shipping_amount', 'payment_method', 'payment_method_code', 'status',
    'gross_amount', 'declared_profit', 'notes', 'reference'
  ];
  v_resolve_sku boolean;
  v_new_consumes boolean;
  v_old_consumes boolean;
  v_available integer;
  v_reason text := left(nullif(btrim(coalesce(p_reason, '')), ''), 500);
begin
  perform public.external_sale_require_admin(p_actor_id);
  if p_patch is null or jsonb_typeof(p_patch) <> 'object' then
    raise exception 'EXTERNAL_SALE_INVALID: los cambios no son válidos.';
  end if;
  for v_key in select jsonb_object_keys(p_patch) loop
    if not v_key = any(v_editable) then
      raise exception 'EXTERNAL_SALE_INVALID: el campo % no se puede editar.', v_key;
    end if;
  end loop;

  select * into v_old from public.external_sales where id = p_id for update;
  if not found then
    raise exception 'EXTERNAL_SALE_NOT_FOUND';
  end if;
  if v_old.status = 'reversed' then
    raise exception 'EXTERNAL_SALE_ALREADY_REVERSED';
  end if;

  v_resolve_sku := p_patch ? 'sku'
    and public.normalized_catalog_sku(p_patch ->> 'sku') is distinct from public.normalized_catalog_sku(v_old.sku);
  v_new := public.external_sale_prepare(
    to_jsonb(v_old) || p_patch
      || case
        when v_resolve_sku and not (p_patch ? 'product_name') then jsonb_build_object('product_name', null)
        else '{}'::jsonb
      end,
    v_old.stock_effect,
    v_resolve_sku
  );

  -- Reintento de una edición ya aplicada: la versión avanzó pero los datos
  -- ya son los pedidos, no es un conflicto.
  if (to_jsonb(v_new) -> 'sale_date', to_jsonb(v_new) -> 'customer_name', to_jsonb(v_new) -> 'channel',
      to_jsonb(v_new) -> 'channel_label', to_jsonb(v_new) -> 'sku', to_jsonb(v_new) -> 'product_id',
      to_jsonb(v_new) -> 'variant_id', to_jsonb(v_new) -> 'product_name', to_jsonb(v_new) -> 'quantity',
      to_jsonb(v_new) -> 'shipping_amount', to_jsonb(v_new) -> 'payment_method',
      to_jsonb(v_new) -> 'payment_method_code', to_jsonb(v_new) -> 'status',
      to_jsonb(v_new) -> 'gross_amount', to_jsonb(v_new) -> 'declared_profit',
      to_jsonb(v_new) -> 'notes', to_jsonb(v_new) -> 'reference')
     is not distinct from
     (to_jsonb(v_old) -> 'sale_date', to_jsonb(v_old) -> 'customer_name', to_jsonb(v_old) -> 'channel',
      to_jsonb(v_old) -> 'channel_label', to_jsonb(v_old) -> 'sku', to_jsonb(v_old) -> 'product_id',
      to_jsonb(v_old) -> 'variant_id', to_jsonb(v_old) -> 'product_name', to_jsonb(v_old) -> 'quantity',
      to_jsonb(v_old) -> 'shipping_amount', to_jsonb(v_old) -> 'payment_method',
      to_jsonb(v_old) -> 'payment_method_code', to_jsonb(v_old) -> 'status',
      to_jsonb(v_old) -> 'gross_amount', to_jsonb(v_old) -> 'declared_profit',
      to_jsonb(v_old) -> 'notes', to_jsonb(v_old) -> 'reference') then
    return v_old;
  end if;

  if p_expected_version is distinct from v_old.version then
    raise exception 'EXTERNAL_SALE_VERSION_CONFLICT';
  end if;

  perform public.external_sale_lock_products(array[v_old.product_id, v_new.product_id]);

  v_old_consumes := v_old.product_id is not null
    and public.external_sale_consumes_stock(v_old.stock_effect, v_old.status, null, null);
  v_new_consumes := v_new.product_id is not null
    and public.external_sale_consumes_stock(v_new.stock_effect, v_new.status, null, null);
  if v_new_consumes and (
    not v_old_consumes
    or v_new.product_id is distinct from v_old.product_id
    or v_new.variant_id is distinct from v_old.variant_id
    or v_new.quantity > v_old.quantity
  ) then
    v_available := coalesce(public.external_sale_available_units(v_new.product_id, v_new.variant_id), 0)
      + case
        when v_old_consumes
          and v_new.product_id = v_old.product_id
          and v_new.variant_id is not distinct from v_old.variant_id
        then v_old.quantity
        else 0
      end;
    if v_new.quantity > v_available then
      raise exception 'EXTERNAL_SALE_STOCK_UNAVAILABLE: % tiene % unidades disponibles (descontando reservas web) y la venta pide %.',
        coalesce(v_new.sku, v_new.product_name), greatest(v_available, 0), v_new.quantity;
    end if;
  end if;

  perform public.external_sale_begin_write(p_actor_id);
  update public.external_sales
  set sale_date = v_new.sale_date,
      customer_name = v_new.customer_name,
      channel = v_new.channel,
      channel_label = v_new.channel_label,
      sku = v_new.sku,
      product_id = v_new.product_id,
      variant_id = v_new.variant_id,
      product_name = v_new.product_name,
      quantity = v_new.quantity,
      unit_price = v_new.unit_price,
      gross_amount = v_new.gross_amount,
      fee_amount = v_new.fee_amount,
      shipping_amount = v_new.shipping_amount,
      net_amount = v_new.net_amount,
      payment_method = v_new.payment_method,
      payment_method_code = v_new.payment_method_code,
      status = v_new.status,
      declared_profit = v_new.declared_profit,
      notes = v_new.notes,
      reference = v_new.reference,
      costo_unitario_historico = case
        when v_new.product_id is not distinct from v_old.product_id
          and v_new.variant_id is not distinct from v_old.variant_id
          and v_new.sale_date = v_old.sale_date
        then v_old.costo_unitario_historico
        when v_new.product_id is null then null
        else public.compute_historical_unit_cost(v_new.product_id, v_new.variant_id, v_new.sale_date)
      end,
      version = v_old.version + 1,
      updated_by = p_actor_id,
      updated_at = now(),
      modified_after_import_at = case
        when v_old.import_batch_id is not null then coalesce(v_old.modified_after_import_at, now())
        else v_old.modified_after_import_at
      end
  where id = p_id
  returning * into v_new;

  perform public.external_sale_write_audit(
    'UPDATE', p_id::text, p_actor_id,
    public.external_sale_audit_payload(v_old),
    public.external_sale_audit_payload(v_new)
      || jsonb_build_object('scope', 'external_sale_edit', 'edit_reason', v_reason)
  );
  perform public.external_sale_end_write();
  return v_new;
end;
$$;

-- 9. Anulación / devolución -------------------------------------------------------------

create or replace function public.cancel_external_sale(
  p_id uuid,
  p_kind text,
  p_return_condition text,
  p_reason text,
  p_actor_id uuid,
  p_idempotency_key text,
  p_expected_version integer default null
)
returns public.external_sales
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sale public.external_sales%rowtype;
  v_before public.external_sales%rowtype;
  v_key text := nullif(btrim(coalesce(p_idempotency_key, '')), '');
  v_reason text := nullif(btrim(coalesce(p_reason, '')), '');
begin
  perform public.external_sale_require_admin(p_actor_id);
  if v_key is null or length(v_key) not between 8 and 240 then
    raise exception 'IDEMPOTENCY_KEY_INVALID';
  end if;
  if v_reason is null or length(v_reason) < 10 or length(v_reason) > 500 then
    raise exception 'EXTERNAL_SALE_INVALID: indicá el motivo (entre 10 y 500 caracteres).';
  end if;
  if p_kind = 'entry_error' then
    if p_return_condition is not null then
      raise exception 'EXTERNAL_SALE_INVALID: una venta cargada por error no tiene condición de devolución.';
    end if;
  elsif p_kind = 'return' then
    if p_return_condition is null or p_return_condition not in ('sellable', 'damaged') then
      raise exception 'EXTERNAL_SALE_INVALID: indicá si el producto volvió en condición vendible.';
    end if;
  else
    raise exception 'EXTERNAL_SALE_INVALID: el tipo de anulación no es válido.';
  end if;

  select * into v_sale from public.external_sales where id = p_id for update;
  if not found then
    raise exception 'EXTERNAL_SALE_NOT_FOUND';
  end if;
  if v_sale.status = 'reversed' then
    if v_sale.reversal_idempotency_key = v_key then
      return v_sale;
    end if;
    raise exception 'EXTERNAL_SALE_ALREADY_REVERSED';
  end if;
  if p_expected_version is not null and p_expected_version <> v_sale.version then
    raise exception 'EXTERNAL_SALE_VERSION_CONFLICT';
  end if;

  v_before := v_sale;
  perform public.external_sale_lock_products(array[v_sale.product_id]);
  perform public.external_sale_begin_write(p_actor_id);

  update public.external_sales
  set status = 'reversed',
      reversed_at = now(),
      reversed_by = p_actor_id,
      reversal_reason = v_reason,
      reversal_amount = greatest(coalesce(v_sale.gross_amount, 0), 0),
      reversal_idempotency_key = v_key,
      reversal_kind = p_kind,
      return_condition = p_return_condition,
      version = v_sale.version + 1,
      updated_by = p_actor_id,
      updated_at = now(),
      modified_after_import_at = case
        when v_sale.import_batch_id is not null then coalesce(v_sale.modified_after_import_at, now())
        else v_sale.modified_after_import_at
      end
  where id = p_id
  returning * into v_sale;

  perform public.external_sale_write_audit(
    'UPDATE', p_id::text, p_actor_id,
    public.external_sale_audit_payload(v_before),
    public.external_sale_audit_payload(v_sale) || jsonb_build_object(
      'scope', case when p_kind = 'return' then 'external_sale_return' else 'external_sale_entry_error' end,
      'stock_restored', public.external_sale_consumes_stock(v_before.stock_effect, v_before.status, null, null)
        and v_before.product_id is not null
        and not public.external_sale_consumes_stock(v_sale.stock_effect, v_sale.status, v_sale.reversal_kind, v_sale.return_condition)
    )
  );
  perform public.external_sale_end_write();
  return v_sale;
end;
$$;

-- 10. Previsualización (sólo lectura) ----------------------------------------------------

create or replace function public.external_sale_rows_content_hash(p_rows jsonb)
returns text
language sql
immutable
set search_path = public
as $$
  select encode(sha256(convert_to(coalesce((
    select jsonb_agg(rows.value - 'confirm_duplicate' order by rows.ordinality)
    from jsonb_array_elements(p_rows) with ordinality as rows(value, ordinality)
  ), '[]'::jsonb)::text, 'UTF8')), 'hex');
$$;

create or replace function public.preview_external_sales_import(p_rows jsonb)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_result jsonb := '[]'::jsonb;
  v_row jsonb;
  v_index integer := 0;
  v_resolved record;
  v_hash text;
  v_matches jsonb;
  v_available integer;
  v_previous record;
begin
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) > 2000 then
    raise exception 'EXTERNAL_SALE_IMPORT_TOO_LARGE: se pueden previsualizar hasta 2000 filas.';
  end if;

  for v_row in select value from jsonb_array_elements(p_rows)
  loop
    select * into v_resolved from public.external_sale_resolve_sku(v_row ->> 'sku');
    begin
      v_hash := public.external_sale_content_hash(
        (v_row ->> 'sale_date')::date, v_row ->> 'sku', v_row ->> 'customer_name',
        (v_row ->> 'quantity')::integer, (v_row ->> 'gross_amount')::numeric
      );
    exception when others then
      v_hash := null;
    end;
    select coalesce(jsonb_agg(sales.sale_number order by sales.sale_number), '[]'::jsonb)
    into v_matches
    from public.external_sales sales
    where v_hash is not null and sales.content_hash = v_hash and sales.status <> 'reversed';
    v_available := case
      when v_resolved.resolution in ('ok', 'archived')
        then public.external_sale_available_units(v_resolved.product_id, v_resolved.variant_id)
      else null
    end;

    v_result := v_result || jsonb_build_array(jsonb_build_object(
      'index', v_index,
      'resolution', v_resolved.resolution,
      'product_id', v_resolved.product_id,
      'variant_id', v_resolved.variant_id,
      'product_name', v_resolved.product_name,
      'variant_name', v_resolved.variant_name,
      'available_units', v_available,
      'duplicate_sale_numbers', v_matches
    ));
    v_index := v_index + 1;
  end loop;

  select batches.id, batches.created_at
  into v_previous
  from public.external_sale_import_batches batches
  where batches.content_hash = public.external_sale_rows_content_hash(p_rows)
    and batches.status = 'completed'
  order by batches.created_at desc
  limit 1;

  return jsonb_build_object(
    'rows', v_result,
    'previous_batch', case when v_previous.id is null then null
      else jsonb_build_object('id', v_previous.id, 'created_at', v_previous.created_at) end
  );
end;
$$;

-- 11. Importación de una tanda -------------------------------------------------------------

create or replace function public.import_external_sales_batch(
  p_batch jsonb,
  p_rows jsonb,
  p_actor_id uuid,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existing public.external_sale_import_batches%rowtype;
  v_batch_id uuid;
  v_source text := p_batch ->> 'source';
  v_file_name text := nullif(btrim(coalesce(p_batch ->> 'file_name', '')), '');
  v_stock_mode text := p_batch ->> 'stock_mode';
  v_rows_read integer;
  v_request_hash text;
  v_content_hash text;
  v_row jsonb;
  v_sale public.external_sales%rowtype;
  v_prepared jsonb := '[]'::jsonb;
  v_row_number integer;
  v_seen_rows integer[] := '{}'::integer[];
  v_seen_hashes text[] := '{}'::text[];
  v_hash text;
  v_label text;
  v_shortage record;
  v_imported integer;
begin
  perform public.external_sale_require_admin(p_actor_id);
  if p_idempotency_key is null or length(p_idempotency_key) not between 8 and 240 then
    raise exception 'IDEMPOTENCY_KEY_INVALID';
  end if;
  if p_batch is null or jsonb_typeof(p_batch) <> 'object'
     or v_source is null or v_source not in ('paste', 'file')
     or v_stock_mode is null or v_stock_mode not in ('none', 'consume') then
    raise exception 'EXTERNAL_SALE_INVALID: elegí si la tanda es histórica o nueva.';
  end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) = 0 then
    raise exception 'EXTERNAL_SALE_IMPORT_EMPTY: no hay ventas válidas para importar.';
  end if;
  if jsonb_array_length(p_rows) > 2000 then
    raise exception 'EXTERNAL_SALE_IMPORT_TOO_LARGE: cada tanda puede tener como máximo 2000 ventas.';
  end if;
  begin
    v_rows_read := coalesce((p_batch ->> 'rows_read')::integer, jsonb_array_length(p_rows));
  exception when others then
    raise exception 'EXTERNAL_SALE_INVALID: la cantidad de filas leídas no es válida.';
  end;
  v_rows_read := greatest(v_rows_read, jsonb_array_length(p_rows));

  v_request_hash := encode(sha256(convert_to(
    jsonb_build_object('batch', p_batch, 'rows', p_rows)::text, 'UTF8'
  )), 'hex');
  v_content_hash := public.external_sale_rows_content_hash(p_rows);

  perform pg_advisory_xact_lock(hashtext('external-sale-import'), hashtext(p_idempotency_key));
  select * into v_existing
  from public.external_sale_import_batches
  where idempotency_key = p_idempotency_key;
  if found then
    if v_existing.request_hash is distinct from v_request_hash
       or v_existing.created_by is distinct from p_actor_id then
      raise exception 'IDEMPOTENCY_PAYLOAD_MISMATCH';
    end if;
    return jsonb_build_object(
      'batch_id', v_existing.id, 'imported', v_existing.rows_imported,
      'stock_mode', v_existing.stock_mode, 'replayed', true
    );
  end if;

  for v_row in select value from jsonb_array_elements(p_rows)
  loop
    begin
      v_row_number := (v_row ->> 'source_row_number')::integer;
    exception when others then
      v_row_number := null;
    end;
    if v_row_number is null or v_row_number < 1 then
      raise exception 'EXTERNAL_SALE_IMPORT_INVALID_ROW: hay una fila sin número de origen.';
    end if;
    if v_row_number = any(v_seen_rows) then
      raise exception 'EXTERNAL_SALE_IMPORT_INVALID_ROW: la fila % aparece dos veces.', v_row_number;
    end if;
    v_seen_rows := array_append(v_seen_rows, v_row_number);
    v_label := 'fila ' || v_row_number;

    if v_row ? 'product_id' or v_row ? 'variant_id' then
      raise exception 'EXTERNAL_SALE_IMPORT_INVALID_ROW: %: el producto se identifica sólo por SKU.', v_label;
    end if;
    if v_row -> 'source_values' is not null and v_row -> 'source_values' <> 'null'::jsonb and (
      jsonb_typeof(v_row -> 'source_values') <> 'object'
      or octet_length((v_row -> 'source_values')::text) > 8000
    ) then
      raise exception 'EXTERNAL_SALE_IMPORT_INVALID_ROW: %: la fila original no es válida.', v_label;
    end if;

    begin
      v_sale := public.external_sale_prepare(v_row, v_stock_mode, true, v_label);
    exception when raise_exception then
      raise exception '%', replace(sqlerrm, 'EXTERNAL_SALE_INVALID:', 'EXTERNAL_SALE_IMPORT_INVALID_ROW:');
    end;

    v_prepared := v_prepared || jsonb_build_array(
      to_jsonb(v_sale) || jsonb_build_object(
        'source_row_number', v_row_number,
        'source_values', nullif(v_row -> 'source_values', 'null'::jsonb),
        'duplicate_hash', public.external_sale_content_hash(
          v_sale.sale_date, v_sale.sku, v_sale.customer_name, v_sale.quantity, v_sale.gross_amount
        ),
        'confirm_duplicate', coalesce((v_row ->> 'confirm_duplicate')::boolean, false)
      )
    );
  end loop;

  -- Posibles duplicados: primero el lock por huella, después la comprobación,
  -- para que dos tandas iguales confirmadas a la vez (con claves distintas)
  -- no pasen ambas la advertencia. Las Históricas no siempre bloquean un
  -- producto, por eso no alcanza con el lock por producto.
  perform public.external_sale_lock_content_hashes(array(
    select value ->> 'duplicate_hash' from jsonb_array_elements(v_prepared)
  ));
  for v_row in select value from jsonb_array_elements(v_prepared)
  loop
    v_hash := v_row ->> 'duplicate_hash';
    if (v_row ->> 'confirm_duplicate')::boolean is not true and (
      v_hash = any(v_seen_hashes)
      or exists (
        select 1 from public.external_sales sales
        where sales.content_hash = v_hash and sales.status <> 'reversed'
      )
    ) then
      raise exception 'EXTERNAL_SALE_POSSIBLE_DUPLICATE: la fila % parece repetida. Confirmá que es una venta distinta.',
        v_row ->> 'source_row_number';
    end if;
    v_seen_hashes := array_append(v_seen_hashes, v_hash);
  end loop;

  -- Candados por producto en orden estable (los mismos que usa el checkout).
  perform public.external_sale_lock_products(array(
    select (value ->> 'product_id')::bigint from jsonb_array_elements(v_prepared)
  ));

  if v_stock_mode = 'consume' then
    select targets.sku, targets.requested, targets.available
    into v_shortage
    from (
      select
        min(value ->> 'sku') as sku,
        sum((value ->> 'quantity')::integer) as requested,
        public.external_sale_available_units(
          (value ->> 'product_id')::bigint, nullif(value ->> 'variant_id', '')::bigint
        ) as available
      from jsonb_array_elements(v_prepared)
      group by (value ->> 'product_id')::bigint, nullif(value ->> 'variant_id', '')::bigint
    ) targets
    where targets.requested > coalesce(targets.available, 0)
    limit 1;
    if found then
      raise exception 'EXTERNAL_SALE_STOCK_UNAVAILABLE: % tiene % unidades disponibles (descontando reservas web) y la tanda pide %.',
        v_shortage.sku, greatest(coalesce(v_shortage.available, 0), 0), v_shortage.requested;
    end if;
  end if;

  insert into public.external_sale_import_batches (
    created_by, source, file_name, content_hash, request_hash, stock_mode,
    rows_read, rows_valid, rows_imported, idempotency_key
  ) values (
    p_actor_id, v_source, case when v_source = 'file' then left(v_file_name, 255) end,
    v_content_hash, v_request_hash, v_stock_mode,
    v_rows_read, jsonb_array_length(v_prepared), jsonb_array_length(v_prepared), p_idempotency_key
  ) returning id into v_batch_id;

  perform public.external_sale_begin_write(p_actor_id);
  insert into public.external_sales (
    sale_date, product_id, variant_id, product_name, sku, quantity, unit_price, unit_cost,
    gross_amount, fee_type, fee_value, fee_amount, shipping_amount, other_expense_amount,
    net_amount, payment_method, payment_method_code, customer_name, notes, reference,
    channel, channel_label, status, declared_profit, stock_effect, origin,
    import_batch_id, source_row_number, source_values, created_by, updated_by
  )
  select
    prepared.sale_date, prepared.product_id, prepared.variant_id, prepared.product_name,
    prepared.sku, prepared.quantity, prepared.unit_price, prepared.unit_cost,
    prepared.gross_amount, prepared.fee_type, prepared.fee_value, prepared.fee_amount,
    prepared.shipping_amount, prepared.other_expense_amount, prepared.net_amount,
    prepared.payment_method, prepared.payment_method_code, prepared.customer_name,
    prepared.notes, prepared.reference, prepared.channel, prepared.channel_label,
    prepared.status, prepared.declared_profit, prepared.stock_effect, v_source,
    v_batch_id, prepared.source_row_number, prepared.source_values, p_actor_id, p_actor_id
  from jsonb_populate_recordset(null::public.external_sales, v_prepared) prepared
  order by prepared.source_row_number;
  get diagnostics v_imported = row_count;

  -- Un único evento por tanda: cada venta ya guarda su tanda, fila y valores
  -- importados, así que no se copian 2000 filas comerciales a audit_logs.
  perform public.external_sale_write_audit(
    'INSERT', 'external-sale-import:' || v_batch_id::text, p_actor_id, null,
    jsonb_build_object(
      'scope', 'external_sale_import',
      'batch_id', v_batch_id,
      'source', v_source,
      'file_name', v_file_name,
      'stock_mode', v_stock_mode,
      'rows_read', v_rows_read,
      'rows_imported', v_imported
    )
  );
  perform public.external_sale_end_write();

  return jsonb_build_object(
    'batch_id', v_batch_id, 'imported', v_imported, 'stock_mode', v_stock_mode, 'replayed', false
  );
end;
$$;

-- 12. Deshacer una tanda ------------------------------------------------------------------
-- Anula (no borra) todas las ventas de la tanda en una sola transacción. Si
-- alguna venta fue editada o anulada individualmente, no se hace nada: se
-- revisan una por una.

create or replace function public.revert_external_sale_import_batch(
  p_batch_id uuid,
  p_expected_count integer,
  p_reason text,
  p_actor_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_batch public.external_sale_import_batches%rowtype;
  v_reason text := nullif(btrim(coalesce(p_reason, '')), '');
  v_total integer;
  v_modified integer;
  v_reverted integer;
begin
  perform public.external_sale_require_admin(p_actor_id);
  if v_reason is null or length(v_reason) < 10 or length(v_reason) > 500 then
    raise exception 'EXTERNAL_SALE_INVALID: indicá el motivo (entre 10 y 500 caracteres).';
  end if;

  select * into v_batch
  from public.external_sale_import_batches
  where id = p_batch_id
  for update;
  if not found then
    raise exception 'EXTERNAL_SALE_BATCH_NOT_FOUND';
  end if;
  if v_batch.status = 'reverted' then
    return jsonb_build_object('batch_id', v_batch.id, 'reverted', 0, 'status', 'reverted', 'replayed', true);
  end if;

  perform 1
  from public.external_sales sales
  where sales.import_batch_id = p_batch_id
  order by sales.id
  for update;

  select count(*)::integer,
         count(*) filter (where sales.modified_after_import_at is not null or sales.status = 'reversed')::integer
  into v_total, v_modified
  from public.external_sales sales
  where sales.import_batch_id = p_batch_id;

  if v_modified > 0 then
    raise exception 'EXTERNAL_SALE_BATCH_HAS_MODIFIED_SALES: % ventas de la tanda fueron modificadas o anuladas.', v_modified;
  end if;
  if p_expected_count is distinct from v_total then
    raise exception 'EXTERNAL_SALE_BATCH_CHANGED';
  end if;

  perform public.external_sale_lock_products(array(
    select sales.product_id from public.external_sales sales
    where sales.import_batch_id = p_batch_id and sales.stock_effect = 'consume'
  ));
  perform public.external_sale_begin_write(p_actor_id);

  update public.external_sales
  set status = 'reversed',
      reversed_at = now(),
      reversed_by = p_actor_id,
      reversal_reason = v_reason,
      reversal_amount = greatest(coalesce(gross_amount, 0), 0),
      reversal_idempotency_key = 'batch-undo:' || id::text,
      reversal_kind = 'batch_undo',
      return_condition = null,
      version = version + 1,
      updated_by = p_actor_id,
      updated_at = now()
  where import_batch_id = p_batch_id;
  get diagnostics v_reverted = row_count;

  update public.external_sale_import_batches
  set status = 'reverted',
      reverted_at = now(),
      reverted_by = p_actor_id,
      revert_reason = v_reason
  where id = p_batch_id;

  perform public.external_sale_write_audit(
    'UPDATE', 'external-sale-import:' || p_batch_id::text, p_actor_id,
    jsonb_build_object('status', 'completed', 'rows_imported', v_batch.rows_imported),
    jsonb_build_object(
      'scope', 'external_sale_import_revert',
      'batch_id', p_batch_id,
      'stock_mode', v_batch.stock_mode,
      'reverted', v_reverted,
      'revert_reason', v_reason
    )
  );
  perform public.external_sale_end_write();

  return jsonb_build_object('batch_id', p_batch_id, 'reverted', v_reverted, 'status', 'reverted', 'replayed', false);
end;
$$;

