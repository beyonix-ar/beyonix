-- 4. Recepción en BEYONIX y pérdida en traslado ---------------------------

-- Ítems normalizados (orden por producto, enteros, sin duplicados): base de la
-- validación y de la comparación determinística de idempotencia.
-- p_with_incidents: recepción ({order_item_id, quantity, incident_type?,
-- incident_quantity?}); si no, pérdida ({order_item_id, quantity >= 1}).
create or replace function public.normalize_order_claim_local_pickup_items(p_items jsonb, p_with_incidents boolean)
returns jsonb
language plpgsql
immutable
set search_path = public
as $$
declare
  v_entry jsonb;
  v_id bigint;
  v_quantity integer;
  v_incident text;
  v_incident_quantity integer;
  v_seen bigint[] := '{}';
  v_lines jsonb := '[]'::jsonb;
begin
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 50 then
    raise exception 'CLAIM_LOGISTICS_INVALID';
  end if;
  for v_entry in select value from jsonb_array_elements(p_items) loop
    if jsonb_typeof(v_entry) is distinct from 'object'
       or coalesce(v_entry->>'order_item_id', '') !~ '^[0-9]{1,18}$'
       or coalesce(v_entry->>'quantity', '') !~ '^[0-9]{1,4}$' then
      raise exception 'CLAIM_LOGISTICS_INVALID';
    end if;
    v_id := (v_entry->>'order_item_id')::bigint;
    v_quantity := (v_entry->>'quantity')::integer;
    if v_id = any (v_seen) then raise exception 'CLAIM_LOGISTICS_INVALID'; end if;
    v_seen := v_seen || v_id;
    if not p_with_incidents then
      if v_entry ?| array['incident_type', 'incident_quantity'] or v_quantity < 1 then raise exception 'CLAIM_LOGISTICS_INVALID'; end if;
      v_lines := v_lines || jsonb_build_object('order_item_id', v_id, 'quantity', v_quantity);
      continue;
    end if;
    v_incident := nullif(btrim(coalesce(v_entry->>'incident_type', '')), '');
    -- Novedades sobre lo que llegó. "Cantidad incorrecta" no es el estado de una
    -- unidad recibida: lo que no llegó queda pendiente (faltante), sin incidencia.
    if v_incident is not null and v_incident not in ('producto_distinto', 'faltantes_accesorios', 'paquete_vacio', 'dano_estado', 'otro') then
      raise exception 'CLAIM_LOGISTICS_INVALID';
    end if;
    if v_incident is null then
      if v_entry ? 'incident_quantity' and jsonb_typeof(v_entry->'incident_quantity') <> 'null' then raise exception 'CLAIM_LOGISTICS_INVALID'; end if;
      if v_quantity = 0 then continue; end if;
      v_lines := v_lines || jsonb_build_object('order_item_id', v_id, 'quantity', v_quantity, 'incident_type', null, 'incident_quantity', 0);
      continue;
    end if;
    -- Una novedad siempre recae sobre unidades recibidas (1..recibidas).
    if v_entry ? 'incident_quantity' and jsonb_typeof(v_entry->'incident_quantity') <> 'null' then
      if coalesce(v_entry->>'incident_quantity', '') !~ '^[0-9]{1,4}$' then raise exception 'CLAIM_LOGISTICS_INVALID'; end if;
      v_incident_quantity := (v_entry->>'incident_quantity')::integer;
    else
      v_incident_quantity := v_quantity;
    end if;
    if v_quantity = 0 or v_incident_quantity < 1 or v_incident_quantity > v_quantity then raise exception 'CLAIM_LOGISTICS_INVALID'; end if;
    v_lines := v_lines || jsonb_build_object('order_item_id', v_id, 'quantity', v_quantity, 'incident_type', v_incident, 'incident_quantity', v_incident_quantity);
  end loop;
  if jsonb_array_length(v_lines) = 0 then raise exception 'CLAIM_LOGISTICS_INVALID'; end if;
  return (select jsonb_agg(line order by (line->>'order_item_id')::bigint) from jsonb_array_elements(v_lines) line);
end;
$$;

-- p_items: [{ "order_item_id": n, "quantity": recibidas, "incident_type"?: tipo,
-- "incident_quantity"?: n }]. Sólo lo que llegó: las unidades que faltan siguen
-- pendientes de volver (faltante temporal, sin incidencia) y el retiro queda en
-- recepción parcial. Una novedad (daño, producto distinto, accesorios, paquete
-- vacío, otro) recae sólo sobre unidades recibidas y exige p_note >= 5.
-- Nunca más unidades que las autorizadas a volver (originales con el cliente
-- o el cadete), nunca las ya recibidas ni las perdidas. Idempotente estricta
-- por clave; concurrente-segura por el lock del reclamo.
create or replace function public.confirm_order_claim_local_pickup_reception(
  p_claim_id bigint,
  p_actor_id uuid,
  p_items jsonb,
  p_note text,
  p_idempotency_key text
)
returns public.order_claim_local_pickups
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pickup public.order_claim_local_pickups%rowtype;
  v_items jsonb;
  v_entry jsonb;
  v_item public.orden_items%rowtype;
  v_order_item_id bigint;
  v_quantity integer;
  v_incident text;
  v_incident_quantity integer;
  v_ids bigint[];
  v_lines jsonb := '[]'::jsonb;
  v_total integer := 0;
  v_incidents integer := 0;
  v_pending integer;
  v_note text := left(btrim(coalesce(p_note, '')), 1000);
  v_status text;
begin
  perform public.assert_order_claim_logistics_admin(p_actor_id);
  perform public.lock_order_claim_for_local_pickup(p_claim_id);
  select * into v_pickup from public.order_claim_local_pickups
  where claim_id = p_claim_id and status <> 'cancelado' for update;
  if not found then raise exception 'CLAIM_LOCAL_PICKUP_NOT_FOUND'; end if;
  v_items := public.normalize_order_claim_local_pickup_items(p_items, true);
  if exists (select 1 from jsonb_array_elements(v_items) x where x->>'incident_type' is not null) and length(v_note) < 5 then
    raise exception 'CLAIM_LOGISTICS_NOTE_REQUIRED';
  end if;
  -- Doble clic / reintento con la misma clave y los mismos datos: no se registra
  -- dos veces. Misma clave con otro actor o contenido: conflicto, sin efectos.
  if not public.begin_order_claim_local_pickup_event(p_claim_id, p_idempotency_key, 'local_pickup_reception', p_actor_id,
    jsonb_build_object('items', v_items, 'notes', v_note)) then
    return v_pickup;
  end if;
  if v_pickup.picked_up_at is null or v_pickup.status not in ('retirado', 'recibido_parcial', 'incidencia') then
    raise exception 'CLAIM_LOCAL_PICKUP_NOT_COLLECTED';
  end if;

  for v_entry in select value from jsonb_array_elements(v_items) loop
    v_order_item_id := (v_entry->>'order_item_id')::bigint;
    v_quantity := (v_entry->>'quantity')::integer;
    v_incident := v_entry->>'incident_type';
    v_incident_quantity := (v_entry->>'incident_quantity')::integer;
    select * into v_item from public.orden_items i
    where i.id = v_order_item_id
      and exists (select 1 from public.order_claim_units u where u.claim_id = p_claim_id and u.order_item_id = i.id and u.role = 'original');
    if not found then raise exception 'CLAIM_UNITS_NOT_AVAILABLE'; end if;

    select array_agg(id order by id) into v_ids from (
      select id from public.order_claim_units
      where claim_id = p_claim_id and role = 'original' and order_item_id = v_order_item_id
        and location = 'con_cliente' and shipment_id is null
      order by id
      limit v_quantity
      for update
    ) picked;
    if coalesce(array_length(v_ids, 1), 0) < v_quantity then raise exception 'CLAIM_UNITS_NOT_AVAILABLE'; end if;

    update public.order_claim_units
    set location = 'recibida_beyonix', updated_at = clock_timestamp()
    where id = any (v_ids);
    -- La novedad, sólo sobre la cantidad afectada de lo recibido.
    if v_incident is not null then
      update public.order_claim_units
      set incident_open = true, incident_type = v_incident,
          incident_note = left(concat_ws(E'\n', incident_note, v_note), 2000), updated_at = clock_timestamp()
      where id = any (v_ids[1:v_incident_quantity]);
      v_incidents := v_incidents + v_incident_quantity;
    end if;
    select count(*) into v_pending from public.order_claim_units
    where claim_id = p_claim_id and role = 'original' and order_item_id = v_order_item_id
      and location = 'con_cliente' and shipment_id is null;
    v_total := v_total + v_quantity;
    v_lines := v_lines || jsonb_build_object(
      'orderItemId', v_item.id, 'productId', v_item.producto_id, 'variantId', v_item.variante_id,
      'conditionedStockId', to_jsonb(v_item) -> 'conditioned_stock_id',
      'quantity', v_quantity, 'incidentType', v_incident,
      'incidentQuantity', case when v_incident is null then 0 else v_incident_quantity end,
      'pendingAfter', v_pending, 'unitIds', to_jsonb(v_ids));
  end loop;

  insert into public.order_claim_local_pickup_receptions (pickup_id, claim_id, actor_id, received_at, items, note, idempotency_key)
  values (v_pickup.id, p_claim_id, p_actor_id, clock_timestamp(), v_lines, nullif(v_note, ''), p_idempotency_key);

  v_status := public.order_claim_local_pickup_physical_status(p_claim_id, v_pickup.status);
  update public.order_claim_local_pickups
  set status = v_status,
      received_at = clock_timestamp(),
      incident_note = null,
      incident_at = null,
      updated_at = clock_timestamp()
  where id = v_pickup.id
  returning * into v_pickup;
  perform public.log_order_claim_logistics(p_claim_id, p_actor_id, 'claim_local_pickup_received',
    jsonb_build_object('pickupId', v_pickup.id, 'items', v_lines, 'received', v_total, 'incidents', v_incidents,
      'status', v_status, 'notes', nullif(v_note, '')));
  if v_status = 'recibido' then
    perform public.post_order_claim_system_message(p_claim_id, 'local_pickup_received:' || v_pickup.id,
      'Recibimos tu producto en BEYONIX. Lo vamos a revisar y te avisamos por este medio cómo sigue.');
  elsif v_status = 'recibido_parcial' then
    perform public.post_order_claim_system_message(p_claim_id, 'local_pickup_partial:' || v_pickup.id,
      'Recibimos parte de tu devolución en BEYONIX. Te avisamos por este medio cómo sigue.');
  end if;
  return v_pickup;
end;
$$;

-- "Pérdida confirmada en traslado": el cadete retiró las unidades y se confirma
-- administrativamente que nunca llegarán a BEYONIX. Excepción controlada SÓLO
-- del retiro comercial local (ver guard_order_claim_unit_transit_loss):
--   * exige admin, motivo (>= 10) y la confirmación explícita del Admin (API);
--   * sólo unidades todavía pendientes de volver (nunca las recibidas, ni más
--     que las pendientes);
--   * no registra recepción ni inspección y nunca devuelve nada a stock;
--   * no emite dinero, notas de crédito ni reemplazos: cierra únicamente la
--     obligación de recepción física de esas unidades para que la resolución
--     comercial siga con sus reglas existentes. La pérdida no es del cliente.
-- p_items: [{ "order_item_id": n, "quantity": n }]. Idempotente estricta.
create or replace function public.confirm_order_claim_local_pickup_loss(
  p_claim_id bigint,
  p_actor_id uuid,
  p_items jsonb,
  p_note text,
  p_idempotency_key text
)
returns public.order_claim_local_pickups
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pickup public.order_claim_local_pickups%rowtype;
  v_items jsonb;
  v_entry jsonb;
  v_item public.orden_items%rowtype;
  v_order_item_id bigint;
  v_quantity integer;
  v_ids bigint[];
  v_lines jsonb := '[]'::jsonb;
  v_total integer := 0;
  v_loss_id bigint;
  v_note text := left(btrim(coalesce(p_note, '')), 1000);
  v_status text;
begin
  perform public.assert_order_claim_logistics_admin(p_actor_id);
  if length(v_note) < 10 then raise exception 'CLAIM_LOGISTICS_NOTE_REQUIRED'; end if;
  perform public.lock_order_claim_for_local_pickup(p_claim_id);
  select * into v_pickup from public.order_claim_local_pickups
  where claim_id = p_claim_id and status <> 'cancelado' for update;
  if not found then raise exception 'CLAIM_LOCAL_PICKUP_NOT_FOUND'; end if;
  v_items := public.normalize_order_claim_local_pickup_items(p_items, false);
  if not public.begin_order_claim_local_pickup_event(p_claim_id, p_idempotency_key, 'local_pickup_loss', p_actor_id,
    jsonb_build_object('items', v_items, 'notes', v_note)) then
    return v_pickup;
  end if;
  -- Sólo después del retiro: antes, el producto sigue con el cliente (se cancela o reprograma).
  if v_pickup.picked_up_at is null or v_pickup.status not in ('retirado', 'recibido_parcial', 'incidencia') then
    raise exception 'CLAIM_LOCAL_PICKUP_NOT_COLLECTED';
  end if;

  for v_entry in select value from jsonb_array_elements(v_items) loop
    v_order_item_id := (v_entry->>'order_item_id')::bigint;
    v_quantity := (v_entry->>'quantity')::integer;
    select * into v_item from public.orden_items i
    where i.id = v_order_item_id
      and exists (select 1 from public.order_claim_units u where u.claim_id = p_claim_id and u.order_item_id = i.id and u.role = 'original');
    if not found then raise exception 'CLAIM_UNITS_NOT_AVAILABLE'; end if;
    -- Pendientes de volver: nunca una unidad ya recibida, inspeccionada o perdida.
    select array_agg(id order by id) into v_ids from (
      select id from public.order_claim_units
      where claim_id = p_claim_id and role = 'original' and order_item_id = v_order_item_id
        and location = 'con_cliente' and shipment_id is null
      order by id desc
      limit v_quantity
      for update
    ) picked;
    if coalesce(array_length(v_ids, 1), 0) < v_quantity then raise exception 'CLAIM_UNITS_NOT_AVAILABLE'; end if;
    -- Una novedad abierta sobre esas unidades se resuelve antes con su flujo.
    if exists (select 1 from public.order_claim_units where id = any (v_ids) and incident_open) then
      raise exception 'CLAIM_LOGISTICS_INCIDENT';
    end if;
    update public.order_claim_units
    set location = 'perdida_traslado', updated_at = clock_timestamp()
    where id = any (v_ids);
    v_total := v_total + v_quantity;
    v_lines := v_lines || jsonb_build_object(
      'orderItemId', v_item.id, 'productId', v_item.producto_id, 'variantId', v_item.variante_id,
      'conditionedStockId', to_jsonb(v_item) -> 'conditioned_stock_id',
      'quantity', v_quantity, 'unitIds', to_jsonb(v_ids));
  end loop;

  insert into public.order_claim_local_pickup_losses (pickup_id, claim_id, actor_id, declared_at, items, note, idempotency_key)
  values (v_pickup.id, p_claim_id, p_actor_id, clock_timestamp(), v_lines, v_note, p_idempotency_key)
  returning id into v_loss_id;

  v_status := public.order_claim_local_pickup_physical_status(p_claim_id, v_pickup.status);
  update public.order_claim_local_pickups
  set status = v_status,
      loss_confirmed_at = clock_timestamp(),
      incident_note = case when v_status = 'incidencia' then incident_note else null end,
      incident_at = case when v_status = 'incidencia' then incident_at else null end,
      updated_at = clock_timestamp()
  where id = v_pickup.id
  returning * into v_pickup;
  perform public.log_order_claim_logistics(p_claim_id, p_actor_id, 'claim_local_pickup_loss_confirmed',
    jsonb_build_object('pickupId', v_pickup.id, 'lossId', v_loss_id, 'items', v_lines, 'quantity', v_total,
      'status', v_status, 'notes', v_note));
  -- Sin culpar al cliente ni exponer detalles internos.
  perform public.post_order_claim_system_message(p_claim_id, 'local_pickup_loss:' || v_loss_id,
    'Tuvimos un inconveniente durante el traslado de tu producto. No tenés que hacer nada: ya lo estamos resolviendo y te avisamos por este medio cómo sigue.');
  return v_pickup;
end;
$$;

