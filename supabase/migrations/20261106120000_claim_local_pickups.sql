-- "No requiere devolución" (Envío BEYONIX): el cliente conserva el producto,
-- decisión explícita con motivo. La solución comercial no cambia: reemplazo,
-- reintegro o saldo siguen sus reglas (sin unidades pendientes de volver).
create or replace function public.waive_order_claim_local_return(p_claim_id bigint, p_actor_id uuid, p_note text)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_claim public.order_claims%rowtype;
  v_note text := left(btrim(coalesce(p_note, '')), 1000);
  v_count integer;
begin
  perform public.assert_order_claim_logistics_admin(p_actor_id);
  if length(v_note) < 10 then raise exception 'CLAIM_LOGISTICS_NOTE_REQUIRED'; end if;
  v_claim := public.lock_order_claim_for_local_pickup(p_claim_id);
  -- Mixto: la devolución ya se definió por producto en la resolución.
  if not public.order_claim_is_accepted(v_claim)
     or coalesce(v_claim.resolution, '') not in ('cambio_producto', 'reintegro_total', 'reintegro_parcial', 'saldo_a_favor', 'cupon_descuento') then
    raise exception 'CLAIM_LOGISTICS_NOT_ALLOWED';
  end if;
  if not public.order_claim_is_local_delivery(v_claim.order_id) then raise exception 'CLAIM_LOGISTICS_NOT_LOCAL'; end if;
  if exists (select 1 from public.order_claim_local_pickups where claim_id = p_claim_id and status <> 'cancelado') then
    raise exception 'CLAIM_RETURN_ALREADY_STARTED';
  end if;
  if exists (select 1 from public.order_claim_shipments where claim_id = p_claim_id and closed_at is null) then
    raise exception 'CLAIM_LOGISTICS_OPEN';
  end if;
  if exists (select 1 from public.order_claim_units where claim_id = p_claim_id and incident_open) then
    raise exception 'CLAIM_LOGISTICS_INCIDENT';
  end if;
  perform public.ensure_order_claim_original_units(v_claim);
  update public.order_claim_units
  set location = 'conservada_cliente', updated_at = clock_timestamp()
  where claim_id = p_claim_id and role = 'original' and location = 'con_cliente' and shipment_id is null;
  get diagnostics v_count = row_count;
  if v_count = 0 then raise exception 'CLAIM_LOGISTICS_NOT_NEEDED'; end if;
  perform public.log_order_claim_logistics(p_claim_id, p_actor_id, 'claim_original_return_waived',
    jsonb_build_object('mode', 'local_no_return', 'quantity', v_count, 'notes', v_note));
  return v_count;
end;
$$;

-- 6. Guardas ------------------------------------------------------------------

-- Envío BEYONIX nunca abre operaciones Andreani de postventa (sucursal,
-- contrato, etiqueta, tracking). Tampoco se mezclan con un retiro local.
-- Sólo inserciones nuevas: lo histórico queda como está.
create or replace function public.guard_order_claim_shipment_carrier()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.order_claim_is_local_delivery(new.order_id) then raise exception 'CLAIM_LOGISTICS_LOCAL_DELIVERY'; end if;
  if exists (select 1 from public.order_claim_local_pickups where claim_id = new.claim_id and status <> 'cancelado') then
    raise exception 'CLAIM_LOGISTICS_OPEN';
  end if;
  return new;
end;
$$;

drop trigger if exists guard_order_claim_shipment_carrier on public.order_claim_shipments;
create trigger guard_order_claim_shipment_carrier
  before insert on public.order_claim_shipments
  for each row execute function public.guard_order_claim_shipment_carrier();

-- La inspección (stock o baja) sólo alcanza lo que BEYONIX recibió: con un
-- retiro por cadete vigente, nunca unidades que siguen con el cliente o el cadete.
create or replace function public.guard_return_movement_local_pickup()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_claim_id bigint;
  v_total integer := coalesce(new.sellable_quantity, 0) + coalesce(new.discounted_quantity, 0) + coalesce(new.non_sellable_quantity, 0);
  v_received integer;
begin
  if new.order_item_id is null or v_total <= 0 then return new; end if;
  select p.claim_id into v_claim_id
  from public.order_claim_local_pickups p join public.order_claims c on c.id = p.claim_id
  where p.order_id = new.order_id and p.status <> 'cancelado' and c.status not in ('cerrado', 'rechazado')
    and exists (select 1 from public.order_claim_units u
                where u.claim_id = p.claim_id and u.role = 'original' and u.order_item_id = new.order_item_id)
  order by p.id desc limit 1;
  if v_claim_id is null then return new; end if;
  select count(*) into v_received from public.order_claim_units
  where claim_id = v_claim_id and role = 'original' and order_item_id = new.order_item_id and location = 'recibida_beyonix';
  if v_total > v_received then raise exception 'CLAIM_LOCAL_PICKUP_NOT_RECEIVED'; end if;
  return new;
end;
$$;

drop trigger if exists guard_return_movement_local_pickup on public.inventory_return_movements;
create trigger guard_return_movement_local_pickup
  before insert on public.inventory_return_movements
  for each row execute function public.guard_return_movement_local_pickup();

-- Nunca finalizar (ni rechazar) con un retiro coordinado o con el producto en
-- manos del cadete: primero se recibe (o se confirma la pérdida en traslado),
-- se registra la incidencia o se cancela.
create or replace function public.guard_order_claim_local_pickup_close()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status in ('cerrado', 'rechazado') and old.status is distinct from new.status
     and exists (select 1 from public.order_claim_local_pickups
                 where claim_id = new.id and status not in ('cancelado', 'recibido', 'resuelto_con_perdida')) then
    raise exception 'CLAIM_LOCAL_PICKUP_OPEN';
  end if;
  return new;
end;
$$;

drop trigger if exists guard_order_claim_local_pickup_close on public.order_claims;
create trigger guard_order_claim_local_pickup_close
  before update of status on public.order_claims
  for each row execute function public.guard_order_claim_local_pickup_close();

-- 'perdida_traslado' es una excepción exclusiva del retiro por cadete: sólo un
-- original pendiente de volver (con el cliente/cadete, sin tramo Andreani) de un
-- reclamo con retiro local vigente YA retirado llega ahí, y es final (nunca
-- pasa a recibida, stock, baja ni conservada). No sirve para omitir otras
-- recepciones o inspecciones obligatorias.
create or replace function public.guard_order_claim_unit_transit_loss()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    if new.location = 'perdida_traslado' then raise exception 'CLAIM_UNIT_TRANSIT_LOSS_INVALID'; end if;
    return new;
  end if;
  if old.location = 'perdida_traslado' then
    if new.location <> 'perdida_traslado' then raise exception 'CLAIM_UNIT_TRANSIT_LOSS_FINAL'; end if;
    return new;
  end if;
  if new.location = 'perdida_traslado' and (
       old.role <> 'original' or old.location <> 'con_cliente' or old.shipment_id is not null or new.shipment_id is not null
       or not exists (select 1 from public.order_claim_local_pickups p
                      where p.claim_id = old.claim_id and p.status in ('retirado', 'recibido_parcial', 'incidencia')
                        and p.picked_up_at is not null)) then
    raise exception 'CLAIM_UNIT_TRANSIT_LOSS_INVALID';
  end if;
  return new;
end;
$$;

drop trigger if exists guard_order_claim_unit_transit_loss on public.order_claim_units;
create trigger guard_order_claim_unit_transit_loss
  before insert or update on public.order_claim_units
  for each row execute function public.guard_order_claim_unit_transit_loss();

-- Igual que 20261020100000 salvo el cierre: una unidad original con
-- "Pérdida confirmada en traslado" también salda su reemplazo entregado (el
-- producto nunca quedó en poder del cliente).
create or replace function public.guard_order_claim_logistics()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.order_claim_shipments where claim_id = new.id)
     and not exists (select 1 from public.order_claim_units where claim_id = new.id) then
    return new;
  end if;


  -- La resolución no se cambia en silencio con una operación física iniciada.
  if new.resolution is distinct from old.resolution and old.resolution is not null
     and not (new.status = 'rechazado' and new.resolution = 'rechazado') then
    if coalesce(current_setting('beyonix.claim_resolution_switch', true), '') = new.id::text then
      if exists (select 1 from public.order_claim_shipments
                 where claim_id = new.id and direction in ('cambio', 'reemplazo') and status <> 'cancelada'
                   and creation_status in ('processing', 'created', 'manual_review'))
         or exists (select 1 from public.order_claim_units where claim_id = new.id and role = 'reemplazo'
                    and location in ('reservada', 'en_andreani', 'entregada_cliente', 'recibida_beyonix')) then
        raise exception 'CLAIM_LOGISTICS_LOCKED';
      end if;
    elsif exists (select 1 from public.order_claim_shipments
               where claim_id = new.id and status <> 'cancelada'
                 and creation_status in ('processing', 'created', 'manual_review'))
       or exists (select 1 from public.order_claim_units where claim_id = new.id and role = 'reemplazo')
       or exists (select 1 from public.order_claim_units where claim_id = new.id and role = 'original' and location <> 'con_cliente') then
      raise exception 'CLAIM_LOGISTICS_LOCKED';
    end if;
  end if;

  if new.status in ('cerrado', 'rechazado') and old.status is distinct from new.status then
    if exists (select 1 from public.order_claim_shipments
               where claim_id = new.id and (creation_status in ('processing', 'manual_review')
                 or (closed_at is null and creation_status = 'created'))) then
      raise exception 'CLAIM_LOGISTICS_OPEN';
    end if;
    if exists (select 1 from public.order_claim_units where claim_id = new.id and incident_open)
       or exists (select 1 from public.order_claim_shipments where claim_id = new.id and review_required) then
      raise exception 'CLAIM_LOGISTICS_INCIDENT';
    end if;
    if exists (select 1 from public.order_claim_units where claim_id = new.id
               and ((role = 'reemplazo' and location in ('reservada', 'en_andreani', 'recibida_beyonix'))
                 or (role = 'original' and location in ('en_andreani', 'recibida_beyonix')))) then
      raise exception 'CLAIM_LOGISTICS_OPEN';
    end if;
    -- Nunca: producto original en poder del cliente + reemplazo entregado.
    if exists (
      select 1 from (
        select order_item_id,
          count(*) filter (where role = 'reemplazo' and location = 'entregada_cliente') delivered,
          count(*) filter (where role = 'original' and location in ('reincorporada_stock', 'baja', 'conservada_cliente', 'perdida_traslado')) settled
        from public.order_claim_units where claim_id = new.id group by order_item_id
      ) x where x.delivered > x.settled
    ) then
      raise exception 'CLAIM_ORIGINAL_NOT_RETURNED';
    end if;
  end if;
  return new;
end;
$$;

-- Pérdida en traslado = obligación de BEYONIX con el cliente ---------------
-- El cliente entregó el producto y BEYONIX lo perdió: el reclamo NUNCA se
-- cancela ni se rechaza, y sólo se finaliza con la solución EJECUTADA para
-- cada unidad perdida (no basta con elegirla ni con 'resuelto_con_perdida'):
--   * reemplazo: unidad de reemplazo 'entregada_cliente' (reservada no cuenta);
--   * reintegro / saldo: NC 'authorized' y liquidada ('completado'), con
--     renglones de ese producto (order_claim_credited_quantity p_settled).
-- Sin excepción administrativa. Rige para cualquier camino (cancel_order_claim,
-- mutate_admin_order_claim o un UPDATE directo) porque vive en un trigger.

-- true = alguna unidad perdida de este reclamo todavía no tiene su solución ejecutada.
create or replace function public.order_claim_transit_loss_pending(p_claim_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from (
      select order_item_id, count(*)::integer lost
      from public.order_claim_units
      where claim_id = p_claim_id and role = 'original' and location = 'perdida_traslado'
      group by order_item_id
    ) l
    where l.lost > (
      (select count(*)::integer from public.order_claim_units r
       where r.claim_id = p_claim_id and r.role = 'reemplazo' and r.order_item_id = l.order_item_id and r.location = 'entregada_cliente')
      + public.order_claim_credited_quantity(p_claim_id, l.order_item_id, 'external_refund', true)
      + public.order_claim_credited_quantity(p_claim_id, l.order_item_id, 'customer_balance', true)
    )
  )
$$;

create or replace function public.guard_order_claim_transit_loss_terminal()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status not in ('cerrado', 'rechazado') or old.status is not distinct from new.status
     or not exists (select 1 from public.order_claim_units
                    where claim_id = new.id and role = 'original' and location = 'perdida_traslado') then
    return new;
  end if;
  -- Cancelar = interrumpir sin solución: con un producto perdido por BEYONIX, nunca.
  if new.cancelled_at is not null then raise exception 'CLAIM_CANCEL_TRANSIT_LOSS'; end if;
  if new.status = 'rechazado' or public.order_claim_transit_loss_pending(new.id) then
    raise exception 'CLAIM_TRANSIT_LOSS_UNRESOLVED';
  end if;
  return new;
end;
$$;

drop trigger if exists guard_order_claim_transit_loss_terminal on public.order_claims;
create trigger guard_order_claim_transit_loss_terminal
  before update of status on public.order_claims
  for each row execute function public.guard_order_claim_transit_loss_terminal();

