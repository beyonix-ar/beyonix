  note text not null check (length(btrim(note)) between 10 and 1000),
  idempotency_key text not null unique
);
create index if not exists order_claim_local_pickup_losses_pickup_idx
  on public.order_claim_local_pickup_losses (pickup_id, declared_at);

comment on table public.order_claim_local_pickup_losses is
  'Pérdida confirmada en traslado (retiro por cadete, Envío BEYONIX): unidades retiradas que nunca llegarán. Cierra sólo la obligación de recepción física; no simula recepción, inspección ni stock.';

