-- Postventa de pedidos Envío BEYONIX: devolución por RETIRO DE UN CADETE,
-- dentro del mismo reclamo (Revisar -> Logística -> Finalizar).
--
-- Reutiliza la infraestructura existente del reclamo:
--   * order_claim_units: paradero de cada unidad. El original queda
--     'con_cliente' hasta que BEYONIX confirma la recepción; pasa a
--     'recibida_beyonix' (pendiente de inspección) y la inspección existente
--     (process_claim_return_inventory -> inventory_return_movements) lo lleva a
--     'reincorporada_stock' o 'baja'. Nada de esto toca stock por sí solo.
--   * order_claim_unit_events: idempotencia de la recepción.
--   * log_order_claim_logistics / post_order_claim_system_message: auditoría y
--     mensaje al cliente en la conversación del reclamo.
--   * create_order_replacement + confirm_order_claim_replacement_delivered_manually:
--     reemplazo reservado y entregado sin Andreani.
--
-- No usa sucursales, contratos, etiquetas, tracking ni envíos Andreani, ni
-- códigos de barras / QR. Tampoco se mezcla con el retorno logístico de Envío
-- BEYONIX tras dos visitas fallidas (local_delivery_shipments y su recepción):
-- tablas, estados y RPCs propios, ligados sólo al reclamo.
--
-- Estados del retiro (order_claim_local_pickups.status):
--   pendiente_coordinacion -> coordinado (fecha acordada, opcional)
--   -> retirado (el cadete tiene el producto; BEYONIX todavía NO lo recibió)
--   -> recibido_parcial / recibido (recepción confirmada en BEYONIX)
--   incidencia: retiro fallido o faltantes; cancelado: antes de retirar.
-- "Pendiente de inspección" no es un estado del retiro: son las unidades en
-- 'recibida_beyonix' (fuente única: order_claim_units).
begin;

-- 1. Tablas ----------------------------------------------------------------

create table if not exists public.order_claim_local_pickups (
  id bigint generated by default as identity primary key,
  claim_id bigint not null references public.order_claims(id) on delete restrict,
  order_id bigint not null references public.ordenes(id) on delete restrict,
  status text not null default 'pendiente_coordinacion' check (status in (
    'pendiente_coordinacion', 'coordinado', 'retirado', 'recibido_parcial', 'recibido', 'incidencia', 'cancelado')),
  agreed_for date,
  picked_up_at timestamptz,
  picked_up_by uuid,
  pickup_note text check (pickup_note is null or length(pickup_note) <= 1000),
  received_at timestamptz,
  incident_note text check (incident_note is null or length(incident_note) <= 1000),
  incident_at timestamptz,
  cancelled_at timestamptz,
  cancelled_by uuid,
  cancel_reason text check (cancel_reason is null or length(cancel_reason) <= 1000),
  created_by uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint order_claim_local_pickups_cancelled check ((status = 'cancelado') = (cancelled_at is not null)),
  constraint order_claim_local_pickups_collected check (
    status not in ('retirado', 'recibido_parcial', 'recibido') or picked_up_at is not null),
  constraint order_claim_local_pickups_received check (
    status not in ('recibido_parcial', 'recibido') or received_at is not null),
  constraint order_claim_local_pickups_coordinated check (status <> 'coordinado' or agreed_for is not null),
  constraint order_claim_local_pickups_incident check (status <> 'incidencia' or incident_note is not null)
);

comment on table public.order_claim_local_pickups is
  'Retiro por cadete de la devolución de un reclamo de un pedido Envío BEYONIX. Uno vigente por reclamo. No mueve stock: la recepción pasa unidades a recibida_beyonix y la inspección existente decide stock o baja.';

create unique index if not exists order_claim_local_pickups_one_active
  on public.order_claim_local_pickups (claim_id) where status <> 'cancelado';
create index if not exists order_claim_local_pickups_order_idx on public.order_claim_local_pickups (order_id);

create table if not exists public.order_claim_local_pickup_receptions (
  id bigint generated by default as identity primary key,
  pickup_id bigint not null references public.order_claim_local_pickups(id) on delete restrict,
  claim_id bigint not null references public.order_claims(id) on delete restrict,
  actor_id uuid not null,
  received_at timestamptz not null default now(),
  -- Productos, variantes y cantidades recibidas (snapshot del ítem del pedido).
  items jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) > 0),
  note text check (note is null or length(note) <= 1000),
  idempotency_key text not null unique
);
create index if not exists order_claim_local_pickup_receptions_pickup_idx
  on public.order_claim_local_pickup_receptions (pickup_id, received_at);

alter table public.order_claim_local_pickups enable row level security;
alter table public.order_claim_local_pickup_receptions enable row level security;
revoke all on table public.order_claim_local_pickups from public, anon, authenticated;
revoke all on table public.order_claim_local_pickup_receptions from public, anon, authenticated;
grant select on table public.order_claim_local_pickups to service_role;
grant select on table public.order_claim_local_pickup_receptions to service_role;

-- 2. Utilidades -------------------------------------------------------------

-- Pedido Envío BEYONIX según el proveedor efectivo (public.order_shipping_carrier).
create or replace function public.order_claim_is_local_delivery(p_order_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select public.order_shipping_carrier(o) = 'beyonix' from public.ordenes o where o.id = p_order_id), false)
$$;

-- Retiro vigente (no cancelado) del reclamo, o null.
create or replace function public.order_claim_active_local_pickup(p_claim_id bigint)
returns public.order_claim_local_pickups
language sql
stable
security definer
set search_path = public
as $$
  select * from public.order_claim_local_pickups
  where claim_id = p_claim_id and status <> 'cancelado'
  order by id desc limit 1
$$;

-- Logística local en curso o resuelta: retiro vigente o devolución dispensada
-- en un pedido Envío BEYONIX (habilita reservar el reemplazo sin Andreani).
create or replace function public.order_claim_local_logistics_ready(p_claim_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.order_claims c
    where c.id = p_claim_id and public.order_claim_is_local_delivery(c.order_id)
      and (exists (select 1 from public.order_claim_local_pickups p where p.claim_id = c.id and p.status <> 'cancelado')
        or public.order_claim_return_waived(c.id))
  )
$$;

create or replace function public.lock_order_claim_for_local_pickup(p_claim_id bigint)
returns public.order_claims
language plpgsql
security definer
set search_path = public
as $$
declare
  v_claim public.order_claims%rowtype;
begin
  select * into v_claim from public.order_claims where id = p_claim_id for update;
  if not found then raise exception 'CLAIM_NOT_FOUND'; end if;
  if v_claim.status in ('cerrado', 'rechazado') then raise exception 'CLAIM_TERMINAL'; end if;
  return v_claim;
end;
$$;

-- 3. Coordinación -----------------------------------------------------------

create or replace function public.request_order_claim_local_pickup(p_claim_id bigint, p_actor_id uuid, p_note text)
returns public.order_claim_local_pickups
language plpgsql
security definer
set search_path = public
as $$
declare
  v_claim public.order_claims%rowtype;
  v_pickup public.order_claim_local_pickups%rowtype;
  v_note text := nullif(left(btrim(coalesce(p_note, '')), 1000), '');
begin
  perform public.assert_order_claim_logistics_admin(p_actor_id);
  v_claim := public.lock_order_claim_for_local_pickup(p_claim_id);
  if not public.order_claim_is_accepted(v_claim)
     or coalesce(v_claim.resolution, '') not in ('cambio_producto', 'reintegro_total', 'reintegro_parcial', 'saldo_a_favor', 'cupon_descuento', 'mixta') then
    raise exception 'CLAIM_LOGISTICS_NOT_ALLOWED';
  end if;
  if not public.order_claim_is_local_delivery(v_claim.order_id) then raise exception 'CLAIM_LOGISTICS_NOT_LOCAL'; end if;
  select * into v_pickup from public.order_claim_local_pickups
  where claim_id = p_claim_id and status <> 'cancelado' for update;
  -- Idempotente: un segundo pedido devuelve el retiro vigente.
  if found then return v_pickup; end if;
  if exists (select 1 from public.order_claim_units where claim_id = p_claim_id and incident_open)
     or exists (select 1 from public.order_claim_shipments where claim_id = p_claim_id and review_required) then
    raise exception 'CLAIM_LOGISTICS_INCIDENT';
  end if;
  if exists (select 1 from public.order_claim_shipments where claim_id = p_claim_id and closed_at is null) then
    raise exception 'CLAIM_LOGISTICS_OPEN';
  end if;
  perform public.ensure_order_claim_original_units(v_claim);
  -- Mixto: sólo vuelven las unidades que su resolución exige.
  if v_claim.resolution = 'mixta' then perform public.sync_mixed_claim_original_units(p_claim_id, p_actor_id); end if;
  if not exists (select 1 from public.order_claim_units
                 where claim_id = p_claim_id and role = 'original' and location = 'con_cliente' and shipment_id is null) then
    raise exception 'CLAIM_LOGISTICS_NOT_NEEDED';
  end if;
  insert into public.order_claim_local_pickups (claim_id, order_id, created_by)
  values (p_claim_id, v_claim.order_id, p_actor_id)
  returning * into v_pickup;
  perform public.log_order_claim_logistics(p_claim_id, p_actor_id, 'claim_local_pickup_requested',
    jsonb_build_object('pickupId', v_pickup.id, 'notes', v_note));
  -- Sin fechas ni horarios: todavía no se acordaron con el cliente.
  perform public.post_order_claim_system_message(p_claim_id, 'local_pickup_requested:' || v_pickup.id,
    'Coordinaremos con vos el retiro del producto en tu domicilio.');
  return v_pickup;
end;
$$;

create or replace function public.schedule_order_claim_local_pickup(p_claim_id bigint, p_actor_id uuid, p_agreed_for date, p_note text)
returns public.order_claim_local_pickups
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pickup public.order_claim_local_pickups%rowtype;
  v_today date := (now() at time zone 'America/Argentina/Buenos_Aires')::date;
begin
  perform public.assert_order_claim_logistics_admin(p_actor_id);
  perform public.lock_order_claim_for_local_pickup(p_claim_id);
  select * into v_pickup from public.order_claim_local_pickups
  where claim_id = p_claim_id and status <> 'cancelado' for update;
  if not found then raise exception 'CLAIM_LOCAL_PICKUP_NOT_FOUND'; end if;
  if v_pickup.picked_up_at is not null or v_pickup.status not in ('pendiente_coordinacion', 'coordinado', 'incidencia') then
    raise exception 'CLAIM_LOCAL_PICKUP_STATE';
  end if;
  if p_agreed_for is null or p_agreed_for < v_today or p_agreed_for > v_today + 60 then
    raise exception 'CLAIM_LOCAL_PICKUP_DATE';
  end if;
  if v_pickup.status = 'coordinado' and v_pickup.agreed_for = p_agreed_for then return v_pickup; end if;
  update public.order_claim_local_pickups
  set status = 'coordinado', agreed_for = p_agreed_for, incident_note = null, incident_at = null, updated_at = clock_timestamp()
  where id = v_pickup.id
  returning * into v_pickup;
  perform public.log_order_claim_logistics(p_claim_id, p_actor_id, 'claim_local_pickup_scheduled',
    jsonb_build_object('pickupId', v_pickup.id, 'agreedFor', p_agreed_for, 'notes', nullif(left(btrim(coalesce(p_note, '')), 1000), '')));
  -- Fecha ya acordada con el cliente: se confirma por escrito (sin horarios).
  perform public.post_order_claim_system_message(p_claim_id, 'local_pickup_scheduled:' || v_pickup.id || ':' || p_agreed_for,
    'Coordinamos el retiro del producto en tu domicilio para el ' || to_char(p_agreed_for, 'DD/MM/YYYY') || '.');
  return v_pickup;
end;
$$;

-- Retiro fallido o faltantes en la recepción: queda en incidencia (con nota)
-- hasta volver a coordinar o completar la recepción.
create or replace function public.report_order_claim_local_pickup_incident(p_claim_id bigint, p_actor_id uuid, p_note text)
returns public.order_claim_local_pickups
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pickup public.order_claim_local_pickups%rowtype;
  v_note text := left(btrim(coalesce(p_note, '')), 1000);
begin
  perform public.assert_order_claim_logistics_admin(p_actor_id);
  if length(v_note) < 5 then raise exception 'CLAIM_LOGISTICS_NOTE_REQUIRED'; end if;
  perform public.lock_order_claim_for_local_pickup(p_claim_id);
  select * into v_pickup from public.order_claim_local_pickups
  where claim_id = p_claim_id and status <> 'cancelado' for update;
  if not found then raise exception 'CLAIM_LOCAL_PICKUP_NOT_FOUND'; end if;
  if v_pickup.status not in ('pendiente_coordinacion', 'coordinado', 'retirado', 'recibido_parcial', 'incidencia') then
    raise exception 'CLAIM_LOCAL_PICKUP_STATE';
  end if;
  update public.order_claim_local_pickups
  set status = 'incidencia', incident_note = v_note, incident_at = clock_timestamp(), updated_at = clock_timestamp()
  where id = v_pickup.id
  returning * into v_pickup;
  perform public.log_order_claim_logistics(p_claim_id, p_actor_id, 'claim_local_pickup_incident',
    jsonb_build_object('pickupId', v_pickup.id, 'collected', v_pickup.picked_up_at is not null, 'notes', v_note));
  return v_pickup;
end;
$$;

-- "Marcar como retirado": el cadete tiene el producto. NO es una recepción:
-- no mueve unidades ni stock, no inspecciona ni cierra nada.
create or replace function public.mark_order_claim_local_pickup_collected(p_claim_id bigint, p_actor_id uuid, p_note text)
returns public.order_claim_local_pickups
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pickup public.order_claim_local_pickups%rowtype;
  v_note text := nullif(left(btrim(coalesce(p_note, '')), 1000), '');
begin
  perform public.assert_order_claim_logistics_admin(p_actor_id);
  perform public.lock_order_claim_for_local_pickup(p_claim_id);
  select * into v_pickup from public.order_claim_local_pickups
  where claim_id = p_claim_id and status <> 'cancelado' for update;
  if not found then raise exception 'CLAIM_LOCAL_PICKUP_NOT_FOUND'; end if;
  if v_pickup.status = 'retirado' then return v_pickup; end if;
  if v_pickup.picked_up_at is not null or v_pickup.status not in ('pendiente_coordinacion', 'coordinado', 'incidencia') then
    raise exception 'CLAIM_LOCAL_PICKUP_STATE';
  end if;
  update public.order_claim_local_pickups
  set status = 'retirado', picked_up_at = clock_timestamp(), picked_up_by = p_actor_id, pickup_note = v_note,
      incident_note = null, incident_at = null, updated_at = clock_timestamp()
  where id = v_pickup.id
  returning * into v_pickup;
  perform public.log_order_claim_logistics(p_claim_id, p_actor_id, 'claim_local_pickup_collected',
    jsonb_build_object('pickupId', v_pickup.id, 'notes', v_note));
  return v_pickup;
end;
$$;

-- 4. Recepción en BEYONIX ---------------------------------------------------

-- p_items: [{ "order_item_id": n, "quantity": n, "incident_type"?: tipo }]
-- (incidencia con el mismo vocabulario de la inspección; exige p_note >= 5).
-- Nunca más unidades que las autorizadas a volver (originales con el cliente
-- de ese reclamo). Idempotente por clave; concurrente-segura por el lock del
-- reclamo (una segunda recepción con otra clave ve las unidades ya movidas).
create or replace function public.confirm_order_claim_local_pickup_reception(
  p_claim_id bigint,
  p_actor_id uuid,
  p_items jsonb,
  p_note text,
  p_idempotency_key text
)
returns public.order_claim_local_pickups
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pickup public.order_claim_local_pickups%rowtype;
  v_entry jsonb;
  v_item public.orden_items%rowtype;
  v_order_item_id bigint;
  v_quantity integer;
  v_incident text;
  v_ids bigint[];
  v_seen bigint[] := '{}';
  v_lines jsonb := '[]'::jsonb;
  v_total integer := 0;
  v_incidents integer := 0;
  v_note text := left(btrim(coalesce(p_note, '')), 1000);
  v_status text;
begin
  perform public.assert_order_claim_logistics_admin(p_actor_id);
  perform public.lock_order_claim_for_local_pickup(p_claim_id);
  select * into v_pickup from public.order_claim_local_pickups
  where claim_id = p_claim_id and status <> 'cancelado' for update;
  if not found then raise exception 'CLAIM_LOCAL_PICKUP_NOT_FOUND'; end if;
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 50 then
    raise exception 'CLAIM_LOGISTICS_INVALID';
  end if;
  -- Doble clic / reintento con la misma clave: no se registra dos veces.
  if not public.begin_order_claim_unit_event(p_claim_id, p_idempotency_key, 'local_pickup_reception', p_actor_id,
    jsonb_build_object('pickupId', v_pickup.id, 'items', p_items, 'notes', v_note)) then
    return v_pickup;
  end if;
  if v_pickup.picked_up_at is null or v_pickup.status not in ('retirado', 'recibido_parcial', 'incidencia') then
    raise exception 'CLAIM_LOCAL_PICKUP_NOT_COLLECTED';
  end if;

  for v_entry in select value from jsonb_array_elements(p_items) loop
    if jsonb_typeof(v_entry) is distinct from 'object'
       or coalesce(v_entry->>'order_item_id', '') !~ '^[0-9]{1,18}$'
       or coalesce(v_entry->>'quantity', '') !~ '^[0-9]{1,4}$' then
      raise exception 'CLAIM_LOGISTICS_INVALID';
    end if;
    v_order_item_id := (v_entry->>'order_item_id')::bigint;
    v_quantity := (v_entry->>'quantity')::integer;
    v_incident := nullif(btrim(coalesce(v_entry->>'incident_type', '')), '');
    if v_order_item_id = any (v_seen) then raise exception 'CLAIM_LOGISTICS_INVALID'; end if;
    v_seen := v_seen || v_order_item_id;
    if v_incident is not null and (
      v_incident not in ('producto_distinto', 'cantidad_incorrecta', 'faltantes_accesorios', 'paquete_vacio', 'dano_estado', 'otro')
      or length(v_note) < 5) then
      raise exception 'CLAIM_LOGISTICS_NOTE_REQUIRED';
    end if;
    if v_quantity = 0 and v_incident is null then continue; end if;
    select * into v_item from public.orden_items i
    where i.id = v_order_item_id
      and exists (select 1 from public.order_claim_units u where u.claim_id = p_claim_id and u.order_item_id = i.id and u.role = 'original');
    if not found then raise exception 'CLAIM_UNITS_NOT_AVAILABLE'; end if;

    select array_agg(id order by id) into v_ids from (
      select id from public.order_claim_units
      where claim_id = p_claim_id and role = 'original' and order_item_id = v_order_item_id
        and location = 'con_cliente' and shipment_id is null
      order by id
      limit greatest(v_quantity, 1)
      for update
    ) picked;
    if coalesce(array_length(v_ids, 1), 0) < greatest(v_quantity, 1) then raise exception 'CLAIM_UNITS_NOT_AVAILABLE'; end if;

    if v_quantity > 0 then
      update public.order_claim_units
      set location = 'recibida_beyonix',
          incident_open = incident_open or v_incident is not null,
          incident_type = coalesce(v_incident, incident_type),
          incident_note = case when v_incident is not null then left(concat_ws(E'\n', incident_note, v_note), 2000) else incident_note end,
          updated_at = clock_timestamp()
      where id = any (v_ids[1:v_quantity]);
    else
      -- Faltante: la unidad sigue pendiente de volver, con su incidencia abierta
      -- (frena dinero y cierre hasta resolverla con el flujo existente).
      update public.order_claim_units
      set incident_open = true, incident_type = v_incident,
          incident_note = left(concat_ws(E'\n', incident_note, v_note), 2000), updated_at = clock_timestamp()
      where id = v_ids[1];
    end if;
    v_total := v_total + v_quantity;
    if v_incident is not null then v_incidents := v_incidents + 1; end if;
    v_lines := v_lines || jsonb_build_object(
      'orderItemId', v_item.id, 'productId', v_item.producto_id, 'variantId', v_item.variante_id,
      'conditionedStockId', to_jsonb(v_item) -> 'conditioned_stock_id',
      'quantity', v_quantity, 'incidentType', v_incident);
  end loop;
  if jsonb_array_length(v_lines) = 0 then raise exception 'CLAIM_LOGISTICS_INVALID'; end if;

  insert into public.order_claim_local_pickup_receptions (pickup_id, claim_id, actor_id, received_at, items, note, idempotency_key)
  values (v_pickup.id, p_claim_id, p_actor_id, clock_timestamp(), v_lines, nullif(v_note, ''), p_idempotency_key);

  v_status := case
    when exists (select 1 from public.order_claim_units
                 where claim_id = p_claim_id and role = 'original' and location = 'con_cliente' and shipment_id is null and incident_open)
      then 'incidencia'
    when exists (select 1 from public.order_claim_units
                 where claim_id = p_claim_id and role = 'original' and location = 'con_cliente' and shipment_id is null)
      then 'recibido_parcial'
    else 'recibido'
  end;
  update public.order_claim_local_pickups
  set status = v_status,
      received_at = case when v_total > 0 then clock_timestamp() else received_at end,
      incident_note = case when v_status = 'incidencia' then left(v_note, 1000) else null end,
      incident_at = case when v_status = 'incidencia' then clock_timestamp() else null end,
      updated_at = clock_timestamp()
  where id = v_pickup.id
  returning * into v_pickup;
  -- Una incidencia sin unidades recibidas (sólo faltantes) igual exige received_at
  -- para 'recibido*'; 'incidencia' no.
  perform public.log_order_claim_logistics(p_claim_id, p_actor_id, 'claim_local_pickup_received',
    jsonb_build_object('pickupId', v_pickup.id, 'items', v_lines, 'received', v_total, 'incidents', v_incidents,
      'status', v_status, 'notes', nullif(v_note, '')));
  if v_status = 'recibido' then
    perform public.post_order_claim_system_message(p_claim_id, 'local_pickup_received:' || v_pickup.id,
      'Recibimos tu producto en BEYONIX. Lo vamos a revisar y te avisamos por este medio cómo sigue.');
  end if;
  return v_pickup;
end;
$$;

-- 5. Cancelar / no requiere devolución ---------------------------------------

-- Sólo antes de que el cadete retire el producto (después, se completa la
-- recepción o se registra la incidencia).
create or replace function public.cancel_order_claim_local_pickup(p_claim_id bigint, p_actor_id uuid, p_note text)
returns public.order_claim_local_pickups
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pickup public.order_claim_local_pickups%rowtype;
  v_note text := left(btrim(coalesce(p_note, '')), 1000);
begin
  perform public.assert_order_claim_logistics_admin(p_actor_id);
  if length(v_note) < 10 then raise exception 'CLAIM_LOGISTICS_NOTE_REQUIRED'; end if;
  perform public.lock_order_claim_for_local_pickup(p_claim_id);
  select * into v_pickup from public.order_claim_local_pickups
  where claim_id = p_claim_id and status <> 'cancelado' for update;
  if not found then raise exception 'CLAIM_LOCAL_PICKUP_NOT_FOUND'; end if;
  if v_pickup.picked_up_at is not null
     or exists (select 1 from public.order_claim_local_pickup_receptions where pickup_id = v_pickup.id) then
    raise exception 'CLAIM_LOCAL_PICKUP_ALREADY_COLLECTED';
  end if;
  update public.order_claim_local_pickups
  set status = 'cancelado', cancelled_at = clock_timestamp(), cancelled_by = p_actor_id, cancel_reason = v_note,
      updated_at = clock_timestamp()
  where id = v_pickup.id
  returning * into v_pickup;
  perform public.log_order_claim_logistics(p_claim_id, p_actor_id, 'claim_local_pickup_cancelled',
    jsonb_build_object('pickupId', v_pickup.id, 'notes', v_note));
  return v_pickup;
end;
$$;

-- "No requiere devolución" (Envío BEYONIX): el cliente conserva el producto,
-- decisión explícita con motivo. La solución comercial no cambia: reemplazo,
-- reintegro o saldo siguen sus reglas (sin unidades pendientes de volver).
create or replace function public.waive_order_claim_local_return(p_claim_id bigint, p_actor_id uuid, p_note text)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_claim public.order_claims%rowtype;
  v_note text := left(btrim(coalesce(p_note, '')), 1000);
  v_count integer;
begin
  perform public.assert_order_claim_logistics_admin(p_actor_id);
  if length(v_note) < 10 then raise exception 'CLAIM_LOGISTICS_NOTE_REQUIRED'; end if;
  v_claim := public.lock_order_claim_for_local_pickup(p_claim_id);
  -- Mixto: la devolución ya se definió por producto en la resolución.
  if not public.order_claim_is_accepted(v_claim)
     or coalesce(v_claim.resolution, '') not in ('cambio_producto', 'reintegro_total', 'reintegro_parcial', 'saldo_a_favor', 'cupon_descuento') then
    raise exception 'CLAIM_LOGISTICS_NOT_ALLOWED';
  end if;
  if not public.order_claim_is_local_delivery(v_claim.order_id) then raise exception 'CLAIM_LOGISTICS_NOT_LOCAL'; end if;
  if exists (select 1 from public.order_claim_local_pickups where claim_id = p_claim_id and status <> 'cancelado') then
    raise exception 'CLAIM_RETURN_ALREADY_STARTED';
  end if;
  if exists (select 1 from public.order_claim_shipments where claim_id = p_claim_id and closed_at is null) then
    raise exception 'CLAIM_LOGISTICS_OPEN';
  end if;
  if exists (select 1 from public.order_claim_units where claim_id = p_claim_id and incident_open) then
    raise exception 'CLAIM_LOGISTICS_INCIDENT';
  end if;
  perform public.ensure_order_claim_original_units(v_claim);
  update public.order_claim_units
  set location = 'conservada_cliente', updated_at = clock_timestamp()
  where claim_id = p_claim_id and role = 'original' and location = 'con_cliente' and shipment_id is null;
  get diagnostics v_count = row_count;
  if v_count = 0 then raise exception 'CLAIM_LOGISTICS_NOT_NEEDED'; end if;
  perform public.log_order_claim_logistics(p_claim_id, p_actor_id, 'claim_original_return_waived',
    jsonb_build_object('mode', 'local_no_return', 'quantity', v_count, 'notes', v_note));
  return v_count;
end;
$$;

-- 6. Guardas ------------------------------------------------------------------

-- Envío BEYONIX nunca abre operaciones Andreani de postventa (sucursal,
-- contrato, etiqueta, tracking). Tampoco se mezclan con un retiro local.
-- Sólo inserciones nuevas: lo histórico queda como está.
create or replace function public.guard_order_claim_shipment_carrier()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.order_claim_is_local_delivery(new.order_id) then raise exception 'CLAIM_LOGISTICS_LOCAL_DELIVERY'; end if;
  if exists (select 1 from public.order_claim_local_pickups where claim_id = new.claim_id and status <> 'cancelado') then
    raise exception 'CLAIM_LOGISTICS_OPEN';
  end if;
  return new;
end;
$$;

drop trigger if exists guard_order_claim_shipment_carrier on public.order_claim_shipments;
create trigger guard_order_claim_shipment_carrier
  before insert on public.order_claim_shipments
  for each row execute function public.guard_order_claim_shipment_carrier();

-- La inspección (stock o baja) sólo alcanza lo que BEYONIX recibió: con un
-- retiro por cadete vigente, nunca unidades que siguen con el cliente o el cadete.
create or replace function public.guard_return_movement_local_pickup()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_claim_id bigint;
  v_total integer := coalesce(new.sellable_quantity, 0) + coalesce(new.discounted_quantity, 0) + coalesce(new.non_sellable_quantity, 0);
  v_received integer;
begin
  if new.order_item_id is null or v_total <= 0 then return new; end if;
  select p.claim_id into v_claim_id
  from public.order_claim_local_pickups p join public.order_claims c on c.id = p.claim_id
  where p.order_id = new.order_id and p.status <> 'cancelado' and c.status not in ('cerrado', 'rechazado')
    and exists (select 1 from public.order_claim_units u
                where u.claim_id = p.claim_id and u.role = 'original' and u.order_item_id = new.order_item_id)
  order by p.id desc limit 1;
  if v_claim_id is null then return new; end if;
  select count(*) into v_received from public.order_claim_units
  where claim_id = v_claim_id and role = 'original' and order_item_id = new.order_item_id and location = 'recibida_beyonix';
  if v_total > v_received then raise exception 'CLAIM_LOCAL_PICKUP_NOT_RECEIVED'; end if;
  return new;
end;
$$;

drop trigger if exists guard_return_movement_local_pickup on public.inventory_return_movements;
create trigger guard_return_movement_local_pickup
  before insert on public.inventory_return_movements
  for each row execute function public.guard_return_movement_local_pickup();

-- Nunca finalizar (ni rechazar) con un retiro coordinado o con el producto en
-- manos del cadete: primero se recibe, se registra la incidencia o se cancela.
create or replace function public.guard_order_claim_local_pickup_close()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status in ('cerrado', 'rechazado') and old.status is distinct from new.status
     and exists (select 1 from public.order_claim_local_pickups
                 where claim_id = new.id and status not in ('cancelado', 'recibido')) then
    raise exception 'CLAIM_LOCAL_PICKUP_OPEN';
  end if;
  return new;
end;
$$;

drop trigger if exists guard_order_claim_local_pickup_close on public.order_claims;
create trigger guard_order_claim_local_pickup_close
  before update of status on public.order_claims
  for each row execute function public.guard_order_claim_local_pickup_close();

-- 7. Reemplazo sin Andreani -----------------------------------------------------
-- Igual que 20261020110000 salvo la condición de plan: en Envío BEYONIX la
-- reserva no exige un tramo Andreani 'cambio'/'reemplazo' abierto, sino el
-- retiro local (con el original ya recibido e inspeccionado) o la devolución
-- dispensada. La entrega se confirma con confirm_order_claim_replacement_delivered_manually.
create or replace function public.create_order_replacement(
  p_original_order_id bigint, p_original_order_item_id bigint,
  p_replacement_variant_id bigint, p_quantity integer, p_reason text,
  p_actor_id uuid, p_idempotency_key text,
  p_condition_note text default null, p_notes text default null, p_claim_id bigint default null
) returns public.order_replacements language plpgsql security definer
set search_path = pg_catalog, public, pg_temp as $$
declare
  v_existing public.order_replacements;
  v_item public.orden_items;
  v_claim public.order_claims;
  v_used integer;
  v_claimed integer;
  v_claim_used integer;
  v_exchange boolean := false;
  v_waived boolean := false;
  v_local boolean := false;
  v_result public.order_replacements;
begin
  if auth.role() is distinct from 'service_role' or not exists (
    select 1 from public.profiles where id = p_actor_id and rol in ('admin','super_admin')
  ) then raise exception 'REPLACEMENT_FORBIDDEN'; end if;
  if p_idempotency_key is null or length(trim(p_idempotency_key)) < 8 then
    raise exception 'REPLACEMENT_IDEMPOTENCY_KEY_REQUIRED';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('replacement:' || p_idempotency_key, 0));
  select * into v_existing from public.order_replacements where idempotency_key = p_idempotency_key;
  if found then
    if v_existing.original_order_id <> p_original_order_id or v_existing.original_order_item_id <> p_original_order_item_id
      or v_existing.replacement_variant_id <> p_replacement_variant_id or v_existing.quantity <> p_quantity
      or v_existing.reason <> p_reason or v_existing.created_by <> p_actor_id
      or v_existing.claim_id is distinct from p_claim_id then raise exception 'REPLACEMENT_CONFLICT'; end if;
    return v_existing;
  end if;

  if p_claim_id is not null then
    select * into v_claim from public.order_claims where id = p_claim_id and order_id = p_original_order_id for update;
    if not found or v_claim.status in ('recibido','en_revision','falta_informacion','cerrado','rechazado')
       or coalesce(v_claim.resolution, '') not in ('cambio_producto', 'envio_unidad_faltante', 'mixta') then
      raise exception 'REPLACEMENT_INVALID_CLAIM';
    end if;
    if v_claim.resolution = 'mixta' then
      v_claimed := nullif(public.order_claim_line_quantity(p_claim_id, p_original_order_item_id, 'replacement'), 0);
    else
      select sum((x->>'quantity')::integer) into v_claimed from jsonb_array_elements(v_claim.affected_items) x
      where (x->>'order_item_id')::bigint = p_original_order_item_id;
    end if;
    if v_claimed is null then raise exception 'REPLACEMENT_INVALID_ITEM'; end if;
    if exists (select 1 from public.order_claim_shipments
               where claim_id = p_claim_id and closed_at is null and direction in ('cambio', 'reemplazo')
                 and creation_status in ('processing', 'created', 'manual_review')) then
      raise exception 'REPLACEMENT_LOGISTICS_LOCKED';
    end if;
    v_exchange := exists (select 1 from public.order_claim_shipments
                          where claim_id = p_claim_id and closed_at is null and direction = 'cambio' and status = 'pendiente');
    v_waived := public.order_claim_return_waived(p_claim_id);
    v_local := public.order_claim_local_logistics_ready(p_claim_id);
    if not v_claim.logistics_legacy and v_claim.resolution in ('cambio_producto', 'mixta')
       and coalesce(v_claim.failure_type, '') not in ('faltante', 'cantidad_menor')
       and not exists (select 1 from public.order_claim_units where claim_id = p_claim_id and role = 'original') then
      raise exception 'REPLACEMENT_REQUIRES_PLAN';
    end if;
    if exists (select 1 from public.order_claim_units where claim_id = p_claim_id and role = 'original') then
      if exists (select 1 from public.order_claim_units where claim_id = p_claim_id and incident_open) then
        raise exception 'REPLACEMENT_REQUIRES_INSPECTION';
      end if;
      if not v_local and not exists (select 1 from public.order_claim_shipments
                     where claim_id = p_claim_id and closed_at is null and status = 'pendiente'
                       and direction in ('cambio', 'reemplazo')) then
        raise exception 'REPLACEMENT_REQUIRES_PLAN';
      end if;
      if v_claim.resolution = 'mixta' then
        -- Mixto: sólo espera la devolución de su propio producto (si la tiene).
        if not public.order_claim_line_return_settled(p_claim_id, p_original_order_item_id, 'replacement') then
          raise exception 'REPLACEMENT_REQUIRES_INSPECTION';
        end if;
      elsif (v_local and not v_waived and not public.order_claim_originals_inspected(p_claim_id))
         or (exists (select 1 from public.order_claim_shipments
                     where claim_id = p_claim_id and closed_at is null and direction = 'reemplazo')
             and not public.order_claim_originals_inspected(p_claim_id)) then
        raise exception 'REPLACEMENT_REQUIRES_INSPECTION';
      end if;
    end if;
  end if;

  select * into v_item from public.orden_items where id = p_original_order_item_id and orden_id = p_original_order_id for update;
  if not found then raise exception 'REPLACEMENT_INVALID_ITEM'; end if;
  select coalesce(sum(quantity - reverted_quantity),0) into v_used
  from public.order_replacements where original_order_item_id = p_original_order_item_id;
  if p_quantity is null or p_quantity <= 0 or p_quantity + v_used > v_item.cantidad then
    raise exception 'REPLACEMENT_QUANTITY_EXCEEDED';
  end if;
  if p_claim_id is not null then
    select coalesce(sum(quantity - reverted_quantity),0) into v_claim_used
    from public.order_replacements where claim_id = p_claim_id and original_order_item_id = p_original_order_item_id;
    if p_quantity + v_claim_used > v_claimed then raise exception 'REPLACEMENT_QUANTITY_EXCEEDED'; end if;
  end if;
  if p_reason <> 'garantia' and not v_exchange and not v_waived and coalesce(v_claim.resolution, '') <> 'mixta'
     and p_quantity + v_used > coalesce(v_item.return_restocked_quantity,0) + coalesce(v_item.return_written_off_quantity,0) then
    raise exception 'REPLACEMENT_REQUIRES_RECEIVED_ITEM';
  end if;
  if not exists (select 1 from public.producto_variantes v join public.productos p on p.id = v.producto_id
    where v.id = p_replacement_variant_id and v.activo and p.activo) then raise exception 'REPLACEMENT_UNAVAILABLE'; end if;
  v_result := public.create_order_replacement_internal(p_original_order_id,p_original_order_item_id,p_replacement_variant_id,
    p_quantity,p_reason,p_actor_id,p_idempotency_key,p_condition_note,p_notes,p_claim_id);
  return v_result;
end;
$$;

