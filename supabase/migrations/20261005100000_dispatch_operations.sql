-- Operational dispatch layer. Andreani's per-order shipment and tracking stay authoritative.
-- All mutations are service_role RPCs with a verified operator; customer order state is unchanged.

alter table public.ordenes
  add column if not exists andreani_handed_over_at timestamptz,
  add column if not exists andreani_handed_over_by uuid,
  add column if not exists andreani_handed_over_batch_id bigint;

create table public.order_packages (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.ordenes(id) on delete restrict,
  status text not null default 'preparing' check (status in ('preparing','prepared')),
  attempt_number integer not null default 1 check (attempt_number > 0),
  prepared_by uuid,
  prepared_at timestamptz,
  created_at timestamptz not null default now(),
  check ((status = 'prepared') = (prepared_at is not null and prepared_by is not null))
);

create table public.order_preparation_lines (
  package_id bigint not null references public.order_packages(id) on delete restrict,
  order_item_id bigint not null unique references public.orden_items(id) on delete restrict,
  product_id bigint not null references public.productos(id) on delete restrict,
  variant_id bigint references public.producto_variantes(id) on delete restrict,
  conditioned_stock_id uuid,
  expected_sku text,
  expected_barcode text,
  expected_quantity integer not null check (expected_quantity > 0),
  scanned_quantity integer not null default 0 check (scanned_quantity >= 0),
  primary key (package_id, order_item_id),
  check (scanned_quantity <= expected_quantity),
  check (expected_sku is not null or expected_barcode is not null)
);

create table public.order_preparation_scans (
  id bigint generated by default as identity primary key,
  package_id bigint not null references public.order_packages(id) on delete restrict,
  attempt_number integer not null check (attempt_number > 0),
  order_item_id bigint not null references public.orden_items(id) on delete restrict,
  request_key uuid not null,
  code text not null,
  scanned_by uuid not null,
  scanned_at timestamptz not null default now(),
  unique (package_id, attempt_number, request_key),
  foreign key (package_id, order_item_id)
    references public.order_preparation_lines(package_id, order_item_id) on delete restrict
);

create table public.order_preparation_resets (
  id bigint generated by default as identity primary key,
  package_id bigint not null references public.order_packages(id) on delete restrict,
  request_key uuid not null,
  attempt_number integer not null check (attempt_number > 1),
  actor_id uuid not null,
  reason text not null check (length(btrim(reason)) >= 10),
  created_at timestamptz not null default now(),
  unique (package_id, request_key),
  unique (package_id, attempt_number)
);

create table public.dispatch_batch_day_sequences (
  dispatch_date date primary key,
  last_number integer not null check (last_number > 0)
);

create table public.dispatch_batches (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^DSP-[0-9]{8}-[0-9]{3,}$'),
  request_key uuid not null unique,
  status text not null default 'open' check (status in ('open','closed','handed_over')),
  created_by uuid not null,
  created_at timestamptz not null default now(),
  closed_by uuid,
  closed_at timestamptz,
  handed_over_by uuid,
  handed_over_at timestamptz,
  check ((status = 'open' and closed_at is null and handed_over_at is null)
      or (status = 'closed' and closed_at is not null and handed_over_at is null)
      or (status = 'handed_over' and closed_at is not null and handed_over_at is not null)),
  check ((closed_at is null) = (closed_by is null)),
  check ((handed_over_at is null) = (handed_over_by is null))
);

alter table public.ordenes add constraint ordenes_handed_over_batch_fk
  foreign key (andreani_handed_over_batch_id) references public.dispatch_batches(id) on delete restrict;
alter table public.ordenes add constraint ordenes_handed_over_pair_check
  check ((andreani_handed_over_at is null and andreani_handed_over_batch_id is null and andreani_handed_over_by is null)
      or (andreani_handed_over_at is not null and andreani_handed_over_batch_id is not null and andreani_handed_over_by is not null));

create table public.dispatch_batch_items (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references public.dispatch_batches(id) on delete restrict,
  package_id bigint not null references public.order_packages(id) on delete restrict,
  order_id bigint not null references public.ordenes(id) on delete restrict,
  added_by uuid not null,
  added_at timestamptz not null default now(),
  removed_by uuid,
  removed_at timestamptz,
  removal_reason text,
  unique (batch_id, order_id),
  check ((removed_at is null and removed_by is null and removal_reason is null)
      or (removed_at is not null and removed_by is not null and length(btrim(removal_reason)) >= 10))
);
create unique index dispatch_batch_items_active_order_unique
  on public.dispatch_batch_items(order_id) where removed_at is null;
create unique index dispatch_batch_items_active_package_unique
  on public.dispatch_batch_items(package_id) where removed_at is null;
create index dispatch_batch_items_active_batch_idx
  on public.dispatch_batch_items(batch_id) where removed_at is null;

create table public.dispatch_batch_events (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references public.dispatch_batches(id) on delete restrict,
  actor_id uuid not null,
  action text not null check (action in ('created','order_added','closed','order_removed','handed_over')),
  order_id bigint references public.ordenes(id) on delete restrict,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index dispatch_batch_events_batch_idx on public.dispatch_batch_events(batch_id,created_at);

create table public.dispatch_blocks (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.ordenes(id) on delete restrict,
  reason text not null check (length(btrim(reason)) between 3 and 120),
  source text not null check (source in ('automatic','manual')),
  created_by uuid,
  created_at timestamptz not null default now(),
  resolved_by uuid,
  resolved_at timestamptz,
  resolution_reason text,
  check ((resolved_at is null and resolved_by is null and resolution_reason is null)
      or (resolved_at is not null and length(btrim(resolution_reason)) >= 10)),
  check (source <> 'manual' or created_by is not null)
);
create unique index dispatch_blocks_active_reason_unique
  on public.dispatch_blocks(order_id, source, reason) where resolved_at is null;
create index dispatch_blocks_active_order_idx
  on public.dispatch_blocks(order_id) where resolved_at is null;

