-- Cancelación de un pedido YA ARMADO: retención física de stock y pausa del
-- circuito de reintegro hasta que el operador confirma el retiro escaneando.
--
-- Auditoría previa (lo que NO cambia):
--   * El stock se descuenta al confirmarse el pago, no al pickear: la venta
--     web es una fila derivada de inventory_movements mientras
--     inventory_order_consumes_stock(estado, payment_status) es verdadera.
--   * Pedido preparado = order_packages.status = 'prepared'; los bultos son
--     order_package_parcels (BX-PKG-…); el lote es dispatch_batches (DSP-…).
--   * El corte financiero de lote cerrado (order_was_prepared_for_dispatch,
--     sólo reintegro manual) sigue igual.
--
-- Problema corregido: al cancelar, la fila de venta desaparecía del ledger y
-- el stock volvía AL INSTANTE aunque las unidades estuvieran embaladas en la
-- mesa de armado o dentro de un lote; además el worker podía emitir la NC y el
-- reintegro sin que nadie hubiera retirado el paquete del circuito.
--
-- Modelo nuevo (mínimo): order_cancellation_holds. Una fila activa significa
-- "el pedido se canceló estando armado y su mercadería sigue fuera de
-- estantería". Mientras exista:
--   1. la venta sigue contando en el ledger (el stock NO vuelve);
--   2. el worker de cancelaciones no toma el pedido;
--   3. no puede iniciarse NC, reintegro MP, resolución financiera ni
--      comprobante de reintegro (cualquier camino, no sólo la UI);
--   4. el lote que lo contiene queda bloqueado (regla existente 'cancelled').
-- Se resuelve UNA vez con resolve_cancelled_order_preparation: escaneo del
-- código del pedido preparado (BX-PREP-…) o de una etiqueta de sus bultos,
-- retiro del lote si correspondía, devolución exacta del stock y auditoría.
-- El código BX-PREP se deriva del armado vigente (pedido + intento), igual
-- que la base de los bultos: no es una entidad nueva.

begin;

-- 1. Retención física -----------------------------------------------------------
create table public.order_cancellation_holds (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.ordenes(id) on delete restrict,
  package_id bigint not null references public.order_packages(id) on delete restrict,
  attempt_number integer not null check (attempt_number > 0),
  batch_id bigint references public.dispatch_batches(id) on delete restrict,
  items jsonb not null check (jsonb_typeof(items) = 'array'),
  units integer not null check (units > 0),
  previous_estado text,
  previous_payment_status text,
  detected_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid,
  resolution_request_key uuid unique,
  resolution_code text,
  resolution_batch_id bigint references public.dispatch_batches(id) on delete restrict,
  check ((resolved_at is null and resolved_by is null and resolution_request_key is null and resolution_code is null)
      or (resolved_at is not null and resolved_by is not null and resolution_request_key is not null and resolution_code is not null))
);
create unique index order_cancellation_holds_active_order_unique
  on public.order_cancellation_holds(order_id) where resolved_at is null;
create index order_cancellation_holds_order_idx on public.order_cancellation_holds(order_id);

alter table public.order_cancellation_holds enable row level security;
revoke all on public.order_cancellation_holds from public, anon, authenticated;
grant select on public.order_cancellation_holds to service_role, authenticated;
create policy order_cancellation_holds_internal_read on public.order_cancellation_holds
  for select to authenticated using (public.is_current_user_internal());

comment on table public.order_cancellation_holds is
  'Pedido cancelado con armado completo: el stock queda retenido y el reintegro en pausa hasta el retiro físico confirmado por escaneo (resolve_cancelled_order_preparation).';

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
