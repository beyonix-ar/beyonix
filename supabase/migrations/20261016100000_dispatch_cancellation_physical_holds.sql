-- 3. Detección: el pedido deja de consumir stock estando armado ----------------
-- AFTER y con este nombre corre antes de refresh_inventory_after_order
-- (orden alfabético): el recálculo ya ve la retención y el stock no se mueve.
create or replace function public.capture_prepared_order_stock_hold()
returns trigger language plpgsql security definer
set search_path = pg_catalog, public, pg_temp as $$
declare
  v_package public.order_packages%rowtype;
  v_items jsonb;
  v_units integer;
  v_batch_id bigint;
  v_hold_id bigint;
begin
  if not public.inventory_order_consumes_stock(old.estado, old.payment_status)
     or public.inventory_order_consumes_stock(new.estado, new.payment_status)
     or new.andreani_handed_over_at is not null then
    return new;
  end if;
  -- Sin lock: el escaneo que completa el armado toma este pedido FOR SHARE
  -- (guard_preparation_scan_active_order), así que una cancelación
  -- concurrente espera a que termine y acá ya ve 'prepared'.
  select * into v_package from public.order_packages where order_id = new.id;
  if not found or v_package.status <> 'prepared'
     or public.order_has_active_stock_hold(new.id) then
    return new;
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('orderItemId', i.id, 'productId', i.producto_id,
           'variantId', i.variante_id, 'conditionedStockId', i.conditioned_stock_id,
           'quantity', i.cantidad) order by i.id), '[]'::jsonb),
         coalesce(sum(i.cantidad), 0)::integer
    into v_items, v_units
    from public.orden_items i where i.orden_id = new.id;
  if v_units <= 0 then return new; end if;
  select batch_id into v_batch_id from public.dispatch_batch_items
    where order_id = new.id and removed_at is null;
  insert into public.order_cancellation_holds(order_id, package_id, attempt_number, batch_id,
      items, units, previous_estado, previous_payment_status)
    values (new.id, v_package.id, v_package.attempt_number, v_batch_id, v_items, v_units,
      old.estado, old.payment_status)
    returning id into v_hold_id;
  insert into public.order_audit_events(order_id, actor_type, actor_id, action, previous_status, new_status, metadata)
    values (new.id, 'system', null, 'dispatch_cancellation_hold_created', 'prepared',
      'requires_physical_resolution', jsonb_build_object('holdId', v_hold_id, 'packageId', v_package.id,
        'attempt', v_package.attempt_number, 'batchId', v_batch_id, 'units', v_units,
        'previousEstado', old.estado, 'newEstado', new.estado));
  return new;
end $$;
create trigger capture_prepared_order_stock_hold
  after update of estado, payment_status on public.ordenes
  for each row execute function public.capture_prepared_order_stock_hold();

-- 4. Guardas de armado ------------------------------------------------------------
-- Ningún escaneo de producto sobre un pedido cancelado (la ruta ya lo
-- rechazaba; esto cierra la carrera con una cancelación concurrente).
create or replace function public.guard_preparation_scan_active_order()
returns trigger language plpgsql security definer
set search_path = pg_catalog, public, pg_temp as $$
declare v_order record;
begin
  select o.estado, o.cancelled_at into v_order
    from public.order_packages p join public.ordenes o on o.id = p.order_id
    where p.id = new.package_id
    for share of o;
  if v_order.estado = 'cancelado' or v_order.cancelled_at is not null then
    raise exception 'DISPATCH_ORDER_BLOCKED';
  end if;
  return new;
end $$;
create trigger guard_preparation_scan_active_order
  before insert on public.order_preparation_scans
  for each row execute function public.guard_preparation_scan_active_order();

-- Un rearmado invalidaría el código escaneado para la resolución.
create or replace function public.guard_package_reset_during_hold()
returns trigger language plpgsql security definer
set search_path = pg_catalog, public, pg_temp as $$
begin
  if new.attempt_number <> old.attempt_number and public.order_has_active_stock_hold(old.order_id) then
    raise exception 'DISPATCH_CANCELLATION_HOLD_ACTIVE';
  end if;
  return new;
end $$;
create trigger guard_package_reset_during_hold
  before update of attempt_number on public.order_packages
  for each row execute function public.guard_package_reset_during_hold();

