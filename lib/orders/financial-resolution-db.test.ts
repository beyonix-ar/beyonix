test("tanda cerrada marca corte histórico y bloquea MP incluso desde el flujo anterior", async () => {
  const db = await setup()
  try {
    await db.exec(`update ordenes set financial_status='payment_confirmed' where id=2;
      insert into dispatch_batches(id,code,request_key,status,created_by)
      values (1,'DSP-20261005-001','30000000-0000-4000-8000-000000000010','open','${actor}');
      insert into order_packages(id,order_id,status,prepared_by,prepared_at)
      values (1,2,'prepared','${actor}',now());
      insert into dispatch_batch_items(batch_id,package_id,order_id,added_by)
      values (1,1,2,'${actor}');
      update dispatch_batches set status='closed',closed_at=now(),closed_by='${actor}' where id=1;
      update ordenes set financial_status='refund_pending' where id=2;`)
    assert.equal((await db.query<{ prepared: boolean }>("select order_was_prepared_for_dispatch(2) prepared")).rows[0].prepared, true)
    await assert.rejects(db.query("select reserve_order_financial_resolution(2,$1,'mercadopago_refund')", [actor]), /FINANCIAL_PREPARED_MANUAL_ONLY/)
    // El corte no depende de la membresía activa (un retiro posterior conserva el historial).
    await db.exec(`update dispatch_batch_items set removed_at=now()+interval '1 minute',
      removed_by='${actor}',removal_reason='Retirado después del cierre' where order_id=2;`)
    assert.equal((await db.query<{ prepared: boolean }>("select order_was_prepared_for_dispatch(2) prepared")).rows[0].prepared, true)
    await assert.rejects(db.exec("insert into mercadopago_order_refunds(order_id,status) values (2,'processing')"), /REFUND_PREPARED_BATCH/)
  } finally { await db.close() }
})

test("reserva e intento son únicos; segundo administrador no toma el lease", async () => {
  const db = await setup()
  try {
    const first = (await db.query<{ id: string }>("select (reserve_order_financial_resolution(1,$1,'manual_refund')).id id", [actor])).rows[0]
    const again = (await db.query<{ id: string }>("select (reserve_order_financial_resolution(1,$1,'manual_refund')).id id", [other])).rows[0]
    assert.equal(first.id, again.id)
    const key1 = "30000000-0000-4000-8000-000000000001"
    const key2 = "30000000-0000-4000-8000-000000000002"
    const one = (await db.query<{ lease_key: string }>("select (claim_order_financial_resolution($1,$2,$3)).lease_key lease_key", [first.id, actor, key1])).rows[0]
    const two = (await db.query<{ lease_key: string }>("select (claim_order_financial_resolution($1,$2,$3)).lease_key lease_key", [first.id, other, key2])).rows[0]
    assert.equal(one.lease_key, key1)
    assert.equal(two.lease_key, key1)
    assert.equal((await db.query<{ n: number }>("select count(*)::int n from order_financial_resolutions where order_id=1")).rows[0].n, 1)
  } finally { await db.close() }
})

test("reintegro manual acepta comprobante ausente y conserva monto, responsable y referencia", async () => {
  const db = await setup()
  try {
    const id = (await db.query<{ id: string }>("select (reserve_order_financial_resolution(1,$1,'manual_refund')).id id", [actor])).rows[0].id
    await db.query("update order_financial_resolutions set status='manual_pending' where id=$1", [id])
    const completed = (await db.query<{ status: string }>("select (complete_manual_order_financial_refund($1,$2,'TRANSFER-123','Reintegro realizado',null)).status status", [id, actor])).rows[0]
    assert.equal(completed.status, "completed")
    const proof = (await db.query<{ amount: number; bank_reference: string; file_path: string | null; uploaded_by: string }>("select amount,bank_reference,file_path,uploaded_by from order_refund_proofs where order_id=1")).rows[0]
    assert.equal(Number(proof.amount), 15000)
    assert.equal(proof.bank_reference, "TRANSFER-123")
    assert.equal(proof.file_path, null)
    assert.equal(proof.uploaded_by, actor)
    await db.query("select complete_manual_order_financial_refund($1,$2,null,null,null)", [id, other])
    assert.equal((await db.query<{ n: number }>("select count(*)::int n from order_refund_proofs where order_id=1")).rows[0].n, 1)
  } finally { await db.close() }
})

