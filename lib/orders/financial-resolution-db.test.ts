test("MP parcial sólo reserva el monto de la NC para reintegro manual", async () => {
  const db = await setup()
  try {
    await db.exec("insert into order_credit_notes(order_id,status,destination,total_amount,cae,settlement_status) values (2,'authorized','external_refund',5000,'CAE-PARCIAL','pendiente')")
    await assert.rejects(db.query("select reserve_order_financial_resolution(2,$1,'mercadopago_refund')", [actor]), /FINANCIAL_MP_INELIGIBLE/)
    const row = (await db.query<{ id: string; amount: number }>("select (r).id,(r).amount from (select reserve_order_financial_resolution(2,$1,'manual_refund') r) s", [actor])).rows[0]
    assert.equal(Number(row.amount), 5000)
    await db.query("update order_financial_resolutions set status='manual_pending' where id=$1", [row.id])
    await db.query("select complete_manual_order_financial_refund($1,$2,null,null,null)", [row.id, actor])
    assert.equal(Number((await db.query<{ amount: number }>("select amount from order_refund_proofs where order_id=2")).rows[0].amount), 5000)
  } finally { await db.close() }
})
