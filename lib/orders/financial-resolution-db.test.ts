test("NC ya autorizada se liquida sin emitir otro comprobante", async () => {
  const db = await setup()
  try {
    await db.exec(`update ordenes set invoice_status='authorized' where id=1;
      insert into order_credit_notes(order_id,status,destination,total_amount,cae,settlement_status)
      values (1,'authorized','external_refund',15000,'CAE-EXISTENTE','pendiente');`)
    const id = (await db.query<{ id: string }>("select (reserve_order_financial_resolution(1,$1,'manual_refund')).id id", [actor])).rows[0].id
    await db.query("update order_financial_resolutions set status='manual_pending' where id=$1", [id])
    await db.query("select complete_manual_order_financial_refund($1,$2,null,null,null)", [id, actor])
    const notes = (await db.query<{ count: number; settlement_status: string }>("select count(*)::int count,max(settlement_status) settlement_status from order_credit_notes where order_id=1")).rows[0]
    assert.equal(notes.count, 1)
    assert.equal(notes.settlement_status, "completado")
  } finally { await db.close() }
})

