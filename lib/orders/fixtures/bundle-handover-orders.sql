-- Columnas reales de producción que necesita la cancelación del cliente
-- (request_customer_order_cancellation_with_claim) y sus avisos. Se aplica
-- después de dispatch-schema.sql; no se suma a ese fixture compartido.
alter table ordenes add column andreani_tracking text;
alter table ordenes add column credit_note_required boolean not null default false;
alter table ordenes add column invoice_number integer;
alter table ordenes add column invoice_point integer;
alter table ordenes add column payment_proof_url text;
alter table ordenes add column payment_id text;
alter table ordenes add column cancellation_requested_by uuid;
alter table ordenes add column refund_method text;
alter table ordenes add column refunded_at timestamptz;
alter table orden_items add column precio numeric default 1000;
alter table order_claims add column user_id uuid, add column claim_type text, add column started_at timestamptz,
  add column description text, add column resolution text, add column offered_resolutions text[],
  add column admin_needs_action boolean, add column last_customer_message_at timestamptz,
  add column affected_items jsonb, add column closed_at timestamptz;
create table order_claim_messages (id bigint generated by default as identity primary key,
  claim_id bigint, author_user_id uuid, author_role text, message text);
create table customer_notifications (id bigint generated by default as identity primary key,
  user_id uuid, type text, title text, body text, action_url text, order_id bigint,
  source_key text unique, is_read boolean not null default false, created_at timestamptz not null default now());
