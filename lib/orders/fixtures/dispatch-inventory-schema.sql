-- Ledger de inventario mínimo con las columnas reales que usan las vistas
-- inventory_movements / conditioned_* y el circuito de cancelación. Se aplica
-- después de dispatch-schema.sql y de las migraciones de despacho.
alter table public.productos add column activo boolean not null default true,
  add column stock integer not null default 0, add column venta_aleatoria boolean not null default false;
alter table public.producto_variantes add column activo boolean not null default true,
  add column stock integer not null default 0, add column nombre text, add column color_hex text,
  add column color_hex_secundario text, add column orden integer;
alter table public.catalog_sku_registry add column conditioned_stock_id uuid;
alter table public.ordenes
  add column created_at timestamptz not null default now(),
  add column usuario_id uuid,
  add column cliente_nombre text,
  add column checkout_idempotency_key text,
  add column invoice_queued_at timestamptz default now(),
  add column cancellation_requested_at timestamptz,
  add column refund_pending_at timestamptz,
  add column auto_cancellation_next_attempt_at timestamptz not null default '-infinity',
  add column auto_cancellation_claimed_until timestamptz,
  add column auto_cancellation_attempts integer not null default 0;
alter table public.orden_items add column return_restocked_quantity integer;

create table public.stock_reservations (session_id text, product_id bigint, variant_id bigint,
  conditioned_stock_id uuid, quantity integer, expires_at timestamptz, order_id bigint);
create table public.checkout_reservation_sessions (session_id text primary key, user_id uuid, order_id bigint,
  reservation_started_at timestamptz, expires_at timestamptz);

create table public.product_cost_entries (id bigint generated by default as identity primary key,
  product_id bigint, variant_id bigint, purchase_date date not null default current_date,
  created_at timestamptz not null default now(), received_quantity integer not null,
  created_by uuid, idempotency_key text, document_number text);
create table public.external_sales (id uuid primary key default gen_random_uuid(), product_id bigint,
  variant_id bigint, sale_date date, created_at timestamptz default now(), quantity integer,
  created_by uuid, reference text, status text default 'active');
create table public.mercadolibre_sales (id bigint generated by default as identity primary key,
  product_id bigint, raw_data jsonb, sale_date timestamptz, imported_at timestamptz default now(),
  quantity integer, imported_by uuid, source_key text, operation_id text, order_id text);
create function public.inventory_ml_variant_id(p_raw jsonb) returns bigint
  language sql immutable as $$ select null::bigint $$;
create function public.inventory_ml_stock_units(p_quantity integer, p_raw jsonb) returns integer
  language sql immutable as $$ select coalesce(p_quantity, 0) $$;
create table public.inventory_return_movements (id uuid primary key default gen_random_uuid(),
  product_id bigint, variant_id bigint, occurred_at timestamptz, created_at timestamptz default now(),
  sellable_quantity integer not null default 0, approved_at timestamptz, approved_by uuid, source_key text,
  mercadolibre_sale_id bigint, order_item_id bigint, conditioned_name text, conditioned_sku text,
  conditioned_color_hex text, conditioned_images jsonb, discounted_quantity integer not null default 0,
  discount_percent numeric, discount_reason text, conditioned_active boolean not null default false);
create table public.business_expenses (id bigint generated by default as identity primary key,
  product_id bigint, variant_id bigint, expense_date date, created_at timestamptz default now(),
  quantity integer, created_by uuid, idempotency_key text, document_number text, expense_type text);
create table public.inventory_stock_adjustments (id bigint generated by default as identity primary key,
  product_id bigint, variant_id bigint, adjustment_date date default current_date,
  created_at timestamptz default now(), quantity_delta integer, created_by uuid,
  idempotency_key text, reason text);
create table public.inventory_variant_allocations (variant_id bigint primary key, quantity integer not null);

