-- Saldo a favor y pagos combinados: columnas reales que usan
-- reverse_customer_credit_for_order y la restitución por NC.
alter table public.ordenes
  add column total numeric not null default 10000,
  add column original_total numeric,
  add column payment_method_id text default 'mercadopago',
  add column credit_balance_used numeric not null default 0,
  add column credit_balance_movement_id uuid,
  add column external_amount_due numeric,
  add column payment_composition jsonb;
alter table public.order_credit_notes
  add column external_amount numeric,
  add column customer_credit_amount numeric not null default 0,
  add column created_by uuid;
create table public.customer_credit_movements (id uuid primary key default gen_random_uuid(),
  user_id uuid, movement_type text, amount numeric, description text, source_type text, source_id text,
  order_id bigint, created_by uuid, related_movement_id uuid, source_key text unique,
  resulting_balance numeric, metadata jsonb, created_at timestamptz not null default now());
create function public.get_customer_credit_balance(p_user_id uuid) returns numeric
  language sql stable as $$ select coalesce(sum(amount), 0) from public.customer_credit_movements where user_id = p_user_id $$;
