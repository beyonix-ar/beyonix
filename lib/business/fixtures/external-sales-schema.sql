-- aplican encima (ver lib/business/external-sales-db.test.ts).
create role anon; create role authenticated; create role service_role;
create schema auth;
create table auth.users (id uuid primary key);
create function auth.role() returns text language sql stable as $$
  select coalesce(nullif(current_setting('request.jwt.claim.role', true), ''), 'service_role') $$;
create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
create table public.profiles (id uuid primary key, rol text not null, email text);
create table public.audit_logs (id bigserial primary key, table_name text not null,
  action text not null check (action in ('INSERT', 'UPDATE', 'DELETE')), record_id text,
  actor_user_id uuid, actor_email text, before_data jsonb, after_data jsonb,
  created_at timestamptz not null default now());
create function public.audit_log_change() returns trigger language plpgsql as $$
begin
  insert into public.audit_logs (table_name, action, record_id, before_data, after_data)
  values (tg_table_name, tg_op,
    case when tg_op = 'DELETE' then old.id::text else new.id::text end,
    case when tg_op <> 'INSERT' then to_jsonb(old) end,
    case when tg_op <> 'DELETE' then to_jsonb(new) end);
  if tg_op = 'DELETE' then return old; end if;
  return new;
end $$;

