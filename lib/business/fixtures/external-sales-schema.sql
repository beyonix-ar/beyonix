-- external_sales tal como quedó antes de 20260921100000 (baseline de producción).
create table public.external_sales (
  id uuid primary key default gen_random_uuid(),
  sale_date date not null default current_date,
  product_id bigint references public.productos(id) on delete set null,
  product_name text not null, sku text,
  quantity integer not null default 1 check (quantity > 0),
  unit_price numeric(12,2) not null default 0, unit_cost numeric(12,2) not null default 0,
  gross_amount numeric(12,2) not null default 0, fee_amount numeric(12,2) not null default 0,
  shipping_amount numeric(12,2) not null default 0 check (shipping_amount >= 0),
  other_expense_amount numeric(12,2) not null default 0, net_amount numeric(12,2) not null default 0,
  payment_method text, reference text, notes text,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  fee_type text not null default 'amount', fee_value numeric(12,2) not null default 0,
  customer_name text,
  variant_id bigint references public.producto_variantes(id) on delete restrict,
  costo_unitario_historico numeric(12,2)
);
create function public.validate_external_sale_variant() returns trigger language plpgsql as $$
begin
  if new.variant_id is not null then
    if not exists (select 1 from public.producto_variantes v where v.id = new.variant_id and v.producto_id = new.product_id) then
      raise exception 'La variante de la venta no pertenece al producto.';
    end if;
  elsif new.product_id is not null and exists (select 1 from public.producto_variantes v where v.producto_id = new.product_id) then
    raise exception 'Seleccioná una variante para descontar correctamente el stock.';
  end if;
  return new;
end $$;
create trigger validate_external_sale_variant before insert or update of product_id, variant_id
  on public.external_sales for each row execute function public.validate_external_sale_variant();
